// city-known-petro.mjs - KNOWN houses of the Petrograd side / Vasilievsky Island extension: appends a generated block (marker PETRO) to src/world/city/known-data.js
//   from the houses tables of the sight dossiers + tools/city-known-petro-curated.mjs and the OSM footprints of src/world/data/city.js.
// usage: node tools/city-known-petro.mjs [--dry] [--print] [--list]
//   (default) writes the block between the PETRO markers at the end of known-data.js (tools/city-known.mjs and city-known-mars.mjs keep foreign blocks when they regenerate theirs)
//   --dry  report only      --print  one line per generated entry      --list  the claimed / placeholder rows
// Tables (docs/research/<name>-houses.json; a missing file is reported and skipped, so the tool is re-run when another sight agent delivers its table):
//   kamennoostrovsky (108 rows: normalised style class, year, socle, features), aurora, strelka, troitskaya, university-embankment, kronverk, vladimir, fortress.
// What a row gives:
//   archetype  from the style class (classic / eclectic / nouveau / nordic / neoclassic / stalin / constructivism / modern) or the free-text style of the other tables
//              (Russian or English): 'nouveau' and 'nordic' -> NORDIC, 'neoclassic' -> NEOCLASSIC1910 from four storeys up, constructivism -> PANEL (plain, flat, grey);
//   storeys    when the dossier differs from the OSM levels; the cornice only when it was estimated on a photo;
//   colours    ONLY photographed walls (`wall`): a `wallGuess` is one typical colour per style class and would paint a whole street in three colours, so those houses take a
//              colour from the palette of their district at run time (district.js, neighbours differ); trim class from `trim`, roof colour from `roof`;
//   features   bay windows, gables (count + shape), turrets (+ top), majolica, rough granite socle, mansard, roof balustrade / attic, half-columns: from `features` / `notes` / `roof`.
// Rows of a house a landmark module claims (layout.GROUPS) are skipped; rows that carry no research (no style, no wall, conf L: "not researched in depth") are skipped too:
// the district-aware default of the grammar decides for them. Matching: by OSM id, else the footprint that contains (x, z). The footprint wins for the plan.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const TABLES = ['kamennoostrovsky', 'aurora', 'strelka', 'troitskaya', 'university-embankment', 'kronverk', 'vladimir', 'fortress'];
const { CURATED } = await import(pathToFileURL(path.join(root, 'tools/city-known-petro-curated.mjs')).href);
const D = await import(pathToFileURL(path.join(root, 'src/world/data/city.js')).href);
const L = await import(pathToFileURL(path.join(root, 'src/world/layout.js')).href);
const KD_FILE = path.join(root, 'src/world/city/known-data.js');
const BEGIN = '// ---- BEGIN PETRO (generated by tools/city-known-petro.mjs: do not edit by hand) ----', BEGIN_RE = /\/\/ ---- BEGIN PETRO /, END = '// ---- END PETRO ----';
const byId = new Map(D.BUILDINGS.map((b) => [b.id, b]));
const RANK = { H: 3, M: 2, L: 1 };

const hexIn = (s) => { const m = /#[0-9a-fA-F]{6}\b/.exec(typeof s === 'string' ? s : ''); return m ? m[0].toLowerCase() : null; };
const rgb = (h) => { const v = parseInt(h.slice(1), 16); return [v >> 16, (v >> 8) & 255, v & 255]; };
const cdist = (a, b) => { const p = rgb(a), q = rgb(b); return Math.hypot(p[0] - q[0], p[1] - q[1], p[2] - q[2]) / 441; };
const lum = (h) => { const [r, g, b] = rgb(h); return (0.299 * r + 0.587 * g + 0.114 * b) / 255; };
const hash01 = (s) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } h ^= h >>> 15; h = Math.imul(h, 2246822519); h ^= h >>> 13; return (h >>> 0) / 4294967296; };
function inRing(o, x, z) { let c = false; for (let i = 0, j = o.length - 2; i < o.length; j = i, i += 2) { const xi = o[i], zi = o[i + 1], xj = o[j], zj = o[j + 1]; if ((zi > z) !== (zj > z) && x < (xj - xi) * (z - zi) / (zj - zi) + xi) c = !c; } return c; }
function trimClassOf(trimS, wall) {
  const th = hexIn(trimS);
  if (!th || !wall) return undefined;
  if (cdist(th, wall) < 0.07) return 2;
  if (lum(th) < 0.62) return 5;
  if (lum(th) < 0.80) return 4;
  const [r, , b] = rgb(th);
  return r - b > 28 ? 3 : 1;
}

// ---------------------------------------------------------------- style -> archetype
const CLASS = { classic: 'CLASSIC', eclectic: 'ECLECTIC', nouveau: 'NORDIC', nordic: 'NORDIC', neoclassic: 'NEOCLASSIC1910', stalin: 'STALIN', constructivism: 'PANEL', modern: 'MODERN' };
function archOf(row, f, year, feat, area) {
  const cls = CLASS[String(row.style || '').toLowerCase()];
  const s = (String(row.style || '') + ' ' + String(row.era || '')).toLowerCase();
  let a = cls || null;
  if (!a) {
    if (/сталин|stalin/.test(s)) a = 'STALIN';
    else if (/constructiv|конструктив/.test(s)) a = 'PANEL';
    else if (/советск|soviet|196\d|197\d|198\d/.test(s)) a = 'PANEL';
    else if (/shed|boiler|garage|frigate|сарай|котельн|гараж|фрегат|корабл/.test(String(row.style || '').toLowerCase())) a = 'SERVICE';       // sheds, garages; a moored ship mapped as a building is a plain dark hull
    else if (/стилизац|20[012]\d|new building|business|бизнес|современн|офисн/.test(s)) a = 'MODERN';
    else if (/northern modern|северный модерн|art nouveau|модерн(?![а-яё])|jugend/.test(s)) a = 'NORDIC';       // (a Cyrillic word has no \b in a JS regex: 'модернизм' is excluded by the lookahead)
    else if (/neoclassic|неокласси/.test(s)) a = 'NEOCLASSIC1910';
    else if (/кирпичн|brick/.test(s)) a = 'BRICK';
    else if (/mansion|особняк/.test(s)) a = f <= 3 ? 'MANSION' : 'ECLECTIC';
    else if (/baroque|барокко|gostiny dvor|trezzini/.test(s) && year && year < 1800) a = 'CLASSIC';                 // 18th-century fronts: low, plain pilasters (the grammar has no baroque)
    else if (/eclectic|эклект|renaissance|baroque|барокко|historicism/.test(s)) a = 'ECLECTIC';
    else if (/classic|класси|empire|ампир|pavilion of/.test(s)) a = 'CLASSIC';
    else if (/service|yard|courtyard|^plain |book stack|флигел|служебн/.test(s)) a = f <= 1 && area < 300 ? 'SERVICE' : 'COURT';
  }
  if (!a) return null;
  // corrections by storeys / year
  if (a === 'NORDIC' && f < 3) a = 'ECLECTIC';
  if (a === 'NEOCLASSIC1910' && f < 4) a = 'CLASSIC';
  if (a === 'CLASSIC' && f >= 5 && !(year && year < 1860)) a = 'ECLECTIC';
  if (a === 'ECLECTIC') {
    if (f <= 2 && /mansion|особняк/.test(feat + ' ' + s)) a = 'MANSION';
    else if (f >= 5 && year >= 1895 && (/bay|erker|эркер|tower|башн/.test(feat) || hash01(row.osm + 'ten') < 0.4)) a = 'TENEMENT';      // late eclectic tenement with bay windows
  }
  return a;
}
// the year that gives the look: the last building phase before 1918 (superstructures count), else the first year mentioned
const yearOf = (row) => { const all = (String(row.year || row.era || '').match(/(1[6-9]\d\d|20[0-2]\d)/g) || []).map(Number); if (!all.length) return 0; const old = all.filter((y) => y <= 1917); return old.length ? Math.max(...old) : all[0]; };

function featuresOf(row, a, f) {
  const t = (String(row.features || '') + ' ' + String(row.notes || '') + ' ' + String(row.roof || '') + ' ' + (CLASS[String(row.style || '').toLowerCase()] ? '' : String(row.style || ''))).toLowerCase();
  const e = {};
  const bay = /bay window|bay windows|erker|эркер|bay turret|tower bay/.test(t);
  const lost = /tower[^.;]{0,30}(is |are )?lost|lost[^.;]{0,30}(tower|tent)|утрачен/.test(t);
  if (a === 'NORDIC' || a === 'TENEMENT' || a === 'ECLECTIC' || a === 'NEOCLASSIC1910') { if (bay) e.er = 1; }
  if (/turret|corner tower|round corner tower|towers|башн|clock tower|belvedere/.test(t) && !(lost && !/towers in the middle/.test(t))) {
    e.tu = 1;
    e.tt = /spire|шпил|needle/.test(t) ? 'spire' : /tent|шатр|pyramid/.test(t) ? 'tent' : /dome|cupola|купол|onion/.test(t) ? (a === 'NORDIC' ? 'helm' : 'dome') : a === 'NORDIC' ? 'helm' : undefined;
    if (!e.tt) delete e.tt;
  }
  if (a === 'NORDIC') {
    if (/stepped attic|stepped gable/.test(t)) { e.gb = 2; e.gs = 3; }
    else if (/horseshoe|round gable|semicircular gable/.test(t)) { e.gb = 1; e.gs = 0; }
    else if (/baroque gable|shaped gable|curved gable|wavy/.test(t)) { e.gb = 1; e.gs = 1; }
    else if (/twin gable|steep gable|gothic/.test(t)) { e.gb = 2; e.gs = 2; }
    else if (/gable|щипц|аттик/.test(t)) e.gb = 1;
    if (/majolica|tile cladding|glazed|ceramic|майолик|изразц/.test(t)) e.mj = 1;
    e.so = /rough granite|rough-hewn/.test(String(row.socle || '') + ' ' + t) || String(row.style).toLowerCase() === 'nordic' ? 1 : 0;
  }
  if (/majolica panels|glazed ceramics/.test(t) && a !== 'NORDIC') e.rich = 1;
  if (/mansard|мансард|seventh a mansard|dormer/.test(t)) e.ms = 1;
  if (a === 'NEOCLASSIC1910' || a === 'STALIN' || a === 'CLASSIC') {
    if (/balustrade|балюстрад/.test(t)) e.pp = 'bal'; else if (/\battic\b|аттик/.test(t)) e.pp = 'attic';
    if (/half-column|columns|колонн/.test(t)) e.col = 1;
    if (/pilaster|relief|пилястр|рельеф|garland|medallion/.test(t)) e.rich = 1;
  }
  if (/two-storey mansion|set back behind a garden|school|училищ|школ|institute|институт|museum|музей|hospital|больниц|palace|дворец|academy|академи|depot|депо|barrack|казарм|laborator|лаборатор|pavilion|horseshoe plan/.test(t + ' ' + String(row.name || '').toLowerCase() + ' ' + String(row.style || '').toLowerCase())) e.shop = false;
  void f;
  return e;
}

// ---------------------------------------------------------------- collect
const rep = { tables: {}, missing: [], rows: 0, idMatch: 0, ptMatch: 0, unmatched: [], claimed: [], dup: 0, placeholder: [], curated: 0, fromRows: 0, partHeight: [], notes: [] };
const rowsAll = [];
for (const t of TABLES) {
  const f = path.join(root, `docs/research/${t}-houses.json`);
  if (!fs.existsSync(f)) { rep.missing.push(t); continue; }
  let arr; try { arr = JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { rep.notes.push(`${t}: unreadable JSON (${e.message})`); rep.missing.push(t); continue; }
  if (!Array.isArray(arr)) arr = arr.houses || arr.rows || Object.values(arr);
  rep.tables[t] = { rows: arr.length, applied: 0, H: 0, M: 0, L: 0 };
  for (const r of arr) rowsAll.push({ ...r, src: t });
}
rowsAll.sort((p, q) => (RANK[q.conf] || 0) - (RANK[p.conf] || 0));          // a house listed in two tables: the better-researched row wins (stable otherwise)
const known = {}, seen = new Set();
for (const row of rowsAll) {
  rep.rows++;
  let b = byId.get(row.osm), how = 'id';
  if (!b && row.x != null) { b = D.BUILDINGS.find((q) => !q.skip && !(q.minH > 3) && q.polys.some((p) => inRing(p.o, row.x, row.z))); how = 'pt'; }
  if (!b) { rep.unmatched.push(`${row.src}: ${row.addr} ${row.osm}`); continue; }
  if (how === 'id') rep.idMatch++; else rep.ptMatch++;
  if (seen.has(b.id)) { rep.dup++; continue; }
  seen.add(b.id);
  if (L.isClaimed(b.id)) { rep.claimed.push(`${b.id} ${L.groupOf(b.id)} ${row.addr || row.name || ''}`); continue; }
  if (CURATED[b.id]) continue;                                              // written below
  const levels = b.levels ? Math.round(b.levels) : 0;
  const f = typeof row.storeys === 'number' && row.storeys > 0 ? row.storeys : levels;
  const year = yearOf(row), wall = hexIn(row.wall);
  const featText = (String(row.features || '') + ' ' + String(row.notes || '')).toLowerCase();
  const researched = !!(row.style || wall || row.features || (row.year && row.year !== null));
  if (!researched) { rep.placeholder.push(`${b.id} ${row.addr || ''}`); continue; }
  const a = archOf(row, f || 4, year, featText, Math.abs(b.area || 0));
  if (!a && !wall) { rep.placeholder.push(`${b.id} ${row.addr || ''} (style not recognised: ${String(row.style).slice(0, 40)})`); continue; }
  const e = { n: String(row.addr || row.name || b.id).slice(0, 48), c: row.conf || 'L', src: row.src };
  if (a) e.a = a;
  if (f && f !== levels) e.f = Math.min(f, 12);
  const photoH = typeof row.hCornice === 'number' && /photo|фото/i.test(String(row.hSource || '')) && (row.conf === 'H' || row.conf === 'M');
  if (photoH && Math.abs(row.hCornice - L.heightOf(b)) > 1) { e.H = Math.round(row.hCornice * 10) / 10; if (!e.f && f) e.f = f; }
  if (wall) e.hex = wall;
  const tc = trimClassOf(row.trim, wall); if (tc !== undefined && a !== 'SERVICE' && a !== 'COURT' && a !== 'NORDIC') e.tr = tc;
  const rh = hexIn(row.roof); if (rh) e.rf = rh;
  if (a) Object.assign(e, featuresOf(row, a, f));
  if (year) e.y = year;
  known[b.id] = e; rep.fromRows++; rep.tables[row.src].applied++; rep.tables[row.src][e.c] = (rep.tables[row.src][e.c] || 0) + 1;
}
// curated records (win over rows; a curated id must exist, be unclaimed and belong to the new regions)
for (const [id, c] of Object.entries(CURATED)) {
  const b = byId.get(id);
  if (!b) { rep.notes.push(`curated id not in the baked data: ${id}`); continue; }
  if (L.isClaimed(id)) { rep.claimed.push(`${id} ${L.groupOf(id)} (curated: skipped)`); continue; }
  known[id] = { n: (b.addr ? `${b.addr.street || ''}, ${b.addr.no || ''}` : b.name || id).slice(0, 48), ...c, src: 'curated' };
  rep.curated++;
}
// parts that would not follow the entry (archetypes.js sameVolume: |heightOf(part) - H| >= 5.6 m keeps its own height)
for (const [id, e] of Object.entries(known)) {
  if (!e.H) continue;
  for (const p of D.BUILDINGS) { if (p.parent !== id) continue; const lv = p.levels || 0, hp = L.heightOf(p); if (lv && (p.minH || 0) <= 0.5 && Math.abs(hp - e.H) >= 5.6) rep.partHeight.push(`${p.id} (part of ${id} ${e.n}) h ${hp.toFixed(1)} vs H ${e.H}`); }
}
const existing = (await import(pathToFileURL(KD_FILE).href + '?t=' + Date.now())).KNOWN_DATA;
const text0 = fs.readFileSync(KD_FILE, 'utf8'), m0 = BEGIN_RE.exec(text0);
const oldBlock = m0 ? text0.slice(m0.index) : '';
for (const id of Object.keys(known)) if (existing[id] && !oldBlock.includes(JSON.stringify(id) + ':')) rep.notes.push(`${id} is also in an older KNOWN block (this block is assigned later and wins)`);

// ---------------------------------------------------------------- report + write
const conf = { H: 0, M: 0, L: 0 }, arch = {};
for (const e of Object.values(known)) { conf[e.c] = (conf[e.c] || 0) + 1; arch[e.a || '-'] = (arch[e.a || '-'] || 0) + 1; }
if (args.has('--print')) for (const [id, e] of Object.entries(known)) console.log(id, JSON.stringify(e));
console.log(JSON.stringify({ rows: rep.rows, matchedById: rep.idMatch, matchedByPoint: rep.ptMatch, unmatched: rep.unmatched.length, duplicates: rep.dup, claimedSkipped: rep.claimed.length, placeholdersSkipped: rep.placeholder.length, entries: Object.keys(known).length, fromRows: rep.fromRows, curated: rep.curated, confidence: conf }));
console.log('tables:', JSON.stringify(rep.tables));
console.log('missing tables (re-run when they arrive):', rep.missing.join(', ') || 'none');
console.log('archetypes:', JSON.stringify(arch));
if (rep.unmatched.length) console.log('unmatched:', rep.unmatched);
if (args.has('--list')) { console.log('claimed (owned by a landmark module):', rep.claimed); console.log('placeholders (the district default decides):', rep.placeholder); }
if (rep.partHeight.length) console.log('parts that keep their own height:', rep.partHeight.length, rep.partHeight.slice(0, 10));
if (rep.notes.length) console.log('notes:', rep.notes);

if (!args.has('--dry')) {
  let text = text0;
  if (m0) { const e = text.indexOf(END, m0.index); const after = e >= 0 ? text.slice(e + END.length).replace(/^\s*/, '') : ''; text = text.slice(0, m0.index).replace(/\s*$/, '\n') + (after ? '\n' + after : ''); }
  if (text.length && !text.endsWith('\n')) text += '\n';
  const lines = Object.entries(known).map(([id, e]) => '  ' + JSON.stringify(id) + ': ' + JSON.stringify(e) + ',');
  const block = `${BEGIN}\n// ${Object.keys(known).length} houses of the Petrograd side / Vasilievsky Island (docs/research/{${Object.keys(rep.tables).join(', ')}}-houses.json + tools/city-known-petro-curated.mjs);\n// c = confidence H / M (dossier, photo-checked or dated), L (knowledge of the place); y = year; no hex = the colour comes from the district palette at run time.\nObject.assign(KNOWN_DATA, {\n${lines.join('\n')}\n});\n${END}\n`;
  fs.writeFileSync(KD_FILE, text + block);
  console.log('wrote', Object.keys(known).length, 'entries into', path.relative(root, KD_FILE));
}
