// The static claims table: which sub-groups every world module declares with `export const OWNS_GROUPS = ...` (a literal: true or a list of keys).
// src/world/lib/claims.js reads the table instead of importing all 40 landmark modules before the first module (environment) can start building:
// those imports (44 MB of code and data) took ~5 s on the critical path of every load. The table is generated from the sources:
//   node tools/owns-table.mjs            writes src/world/lib/owns-table.js
//   node tools/owns-table.mjs --check    exits 1 when the table is stale (run by tools/layout-test.mjs)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src/world'), outFile = path.join(dir, 'lib/owns-table.js');
const table = {};
for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.js')).sort()) {
  const src = fs.readFileSync(path.join(dir, f), 'utf8');
  const m = /^export\s+const\s+OWNS_GROUPS\s*=\s*([^;]+);/m.exec(src);
  if (!m) continue;
  let v;
  try { v = Function(`"use strict"; return (${m[1]});`)(); } catch (e) { throw new Error(`${f}: OWNS_GROUPS is not a literal (${m[1].slice(0, 80)})`); }
  if (v !== true && !Array.isArray(v)) throw new Error(`${f}: OWNS_GROUPS must be true or a list`);
  table[f.replace(/\.js$/, '')] = v;
}
const text = `// GENERATED by tools/owns-table.mjs from the OWNS_GROUPS exports of src/world/*.js: do not edit (re-run the tool after changing a claim; tools/layout-test.mjs checks it).\nexport const OWNS_TABLE = ${JSON.stringify(table, null, 0).replace(/,"/g, ', "').replace(/":/g, '": ')};\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (cur !== text) { console.log('owns-table: STALE (run node tools/owns-table.mjs)'); process.exit(1); }
  console.log(`owns-table: OK (${Object.keys(table).length} modules)`);
} else {
  fs.writeFileSync(outFile, text);
  console.log(`wrote ${path.relative(root, outFile)} (${Object.keys(table).length} modules)`);
}
