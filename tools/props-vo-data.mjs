// props-vo-data: writes src/world/props/vo-data.js, the OSM facts about the street props of Vasilievsky Island that the baked data modules (src/world/data/city-v*.js) lost:
//   * advertising=billboard (54 + 2 on a pole / mast, all lit, two-sided), advertising=totem (9): the baked MANMADE record keeps only kind 'advertising' without its type;
//   * man_made=surveillance (121): the mount (wall / pole) and the camera type (dome / fixed).
// Source: data/osm-raw/manmade.json (the OSM map API fetch of docs/research/vo-roster-architecture.md; data (c) OpenStreetMap contributors, ODbL). Only nodes inside the outline of the island
// (src/world/lib/vo-island.js) are kept; the runtime (props/vo.js) cuts the older, already reviewed districts by itself (inVO). Run: node tools/props-vo-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { inIsland } = await import(pathToFileURL(path.join(root, 'src/world/lib/vo-island.js')).href);
const { proj } = await import(pathToFileURL(path.join(root, 'tools/osm-lib.mjs')).href);
const els = JSON.parse(fs.readFileSync(path.join(root, 'data/osm-raw/manmade.json'), 'utf8')).elements;
const r1 = (v) => Math.round(v * 10) / 10;
const bill = [], totem = [], cctv = [];
for (const e of els) {
  if (e.type !== 'node' || !e.tags) continue;
  const [x, z] = proj(e.lon, e.lat);
  if (!inIsland(x, z)) continue;
  const t = e.tags;
  if (t.advertising === 'billboard') bill.push([r1(x), r1(z), t.support === 'pole' ? 1 : t.support === 'mast' ? 2 : 0]);
  else if (t.advertising === 'totem') totem.push([r1(x), r1(z)]);
  else if (t.man_made === 'surveillance') cctv.push([r1(x), r1(z), 1, t['camera:mount'] === 'pole' ? 2 : t['camera:mount'] === 'wall' ? 1 : 0, t['camera:type'] === 'dome' ? 1 : 0]);
}
const J = (a) => '[' + a.map((q) => '[' + q.join(',') + ']').join(',') + ']';
const out = `// props/vo-data.js - GENERATED by tools/props-vo-data.mjs from data/osm-raw/manmade.json (OpenStreetMap data (c) OpenStreetMap contributors, ODbL). Pure data, local metres (+x east, +z south).
// BILLBOARDS [x, z, support 0 none / 1 pole / 2 mast] (advertising=billboard, all lit, two sides), TOTEMS [x, z] (advertising=totem), CCTV [x, z, 1, mount 0 ? / 1 wall / 2 pole, dome 0 / 1]
// (man_made=surveillance). Nodes inside the outline of Vasilievsky Island only; the older districts are cut at run time (props/vo.js inVO).
export const BILLBOARDS = ${J(bill)};
export const TOTEMS = ${J(totem)};
export const CCTV = ${J(cctv)};
`;
fs.writeFileSync(path.join(root, 'src/world/props/vo-data.js'), out);
console.log('billboards', bill.length, 'totems', totem.length, 'cctv', cctv.length, 'bytes', out.length);
