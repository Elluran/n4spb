// Offline exact island/river outlines, OSM contributors, ODbL.
// Input is the cached full relation extract, not an estimated shore polygon.
import fs from 'node:fs';
import { elementPolys, flat, simplify, bboxOf } from './osm-lib.mjs';
import { splitHoles } from './water-rings.mjs';
const root=new URL('../',import.meta.url);
const source=JSON.parse(fs.readFileSync(new URL('docs/reference/krestovsky-osm.json',root),'utf8'));
const island=source.elements.find(e=>e.id===1576176);
const rings=elementPolys(island);
if(rings.length!==1)throw Error('Expected one complete Krestovsky Island outline');
const islandRing=flat(simplify(rings[0].o,.2));
// 2026-10-13 (islands round 2): a ring with islands in it (the Malaya Nevka round the two islets of the Krestovsky shore) is cut into simple rings along two slits per hole (tools/water-rings.mjs):
// waterways.js reads outer rings only, so a hole used to be flooded. `rel` = the OSM relation, `id` = the piece.
const water=source.elements.filter(e=>e.id!==1576176).flatMap(e=>elementPolys(e).flatMap(p=>{const rs=splitHoles(p);return rs.map((r,i)=>({id:'r'+e.id+(rs.length>1?'.'+i:''),rel:'r'+e.id,name:e.tags.name,key:'neva',o:flat(simplify(r,.15))}))}));
if(new Set(water.map(p=>p.rel)).size!==2)throw Error('Both Nevka waterways must have complete rings');
fs.writeFileSync(new URL('src/world/environment/krestovsky-context.js',root),'// GENERATED by tools/bake-krestovsky-context.mjs. OpenStreetMap contributors, ODbL.\nexport const KRESTOVSKY_ISLAND = '+JSON.stringify(islandRing)+';\nexport const KRESTOVSKY_WATER = '+JSON.stringify(water)+';\n');
console.log('Krestovsky island',bboxOf(rings[0].o),'river rings',water.map(p=>[p.id,p.o.length/2]));
