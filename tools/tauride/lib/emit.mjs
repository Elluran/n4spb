// Turns the derived records (derived.json + union.json of the pipeline) into the text of the pure-data modules src/world/landmarksTauride/data/{water,bridges,paths,furniture,footprints}.js.
// Pure and deterministic: the same inputs give the same bytes (data-test.mjs runs the whole pipeline twice and compares).
import { moduleText, PROVENANCE, inPoly, inPolys, inRing, ringDist, polyLen, bbox, r1, r3, polyArea } from './common.mjs';
import { CANAL_WIDTHS, CANAL_JOIN, CANAL_DRY_RULE, BRIDGE_SITES, BRIDGE_DECK_WIDTH, BRIDGE_EXTEND, PATH_CLASS_RULE, PATH_CLASS_OVERRIDES, FENCE_RULES, LAKE_ID, WEST_POND_ID } from './tables.mjs';
import { bridgeDecks, crossSection } from './derive.mjs';

/** the two ways the old terrain.js did not have (the facade is newer than the 2026-10-03 snapshot): both lie 20-30 m INSIDE the garden polygon */
export const NOT_IN_LEGACY_TERRAIN = ['w425188838', 'w425188839'];
/** the dam, decided from the data (docs/TAURIDE-REMAKE.md section 6.2) */
const DAM_WAY = 'w112880645';
const DAM_REJECTED = { point: [1269, -1655], from: 'the plan text "low weir at the dam (1269,-1655)"' };

const GEN = 'node tools/tauride/build.mjs';
const head = (what, extra = []) => [
  `Tauride Garden data: ${what}. GENERATED by ${GEN} (tools/tauride/*): do not edit by hand, regenerate (tools/tauride/README.md); tools/tauride/data-test.mjs checks it.`,
  `Source: ${PROVENANCE}.`,
  'Frame: metres from ORIGIN, +X east, +Z south (-Z is north), the frame of the whole project. Rings are flat [x, z, x, z, ...] (not closed). Pure data: no imports.',
  ...extra,
].join('\n');

const chainOf = (ways) => {            // concatenate bridge ways that share end points, in walking order
  const rows = ways.map((w) => ({ id: w.id, pts: w.deck.slice() }));
  const key = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]) < 0.2;
  const first = rows.shift();
  const out = first.pts.slice();
  while (rows.length) {
    const tail = [out[out.length - 2], out[out.length - 1]];
    const i = rows.findIndex((r) => key(tail, [r.pts[0], r.pts[1]]) || key(tail, [r.pts[r.pts.length - 2], r.pts[r.pts.length - 1]]));
    if (i < 0) throw new Error('bridge chain is not connected at ' + tail);
    const r = rows.splice(i, 1)[0];
    const fwd = key(tail, [r.pts[0], r.pts[1]]);
    const p = fwd ? r.pts : (() => { const q = []; for (let k = r.pts.length - 2; k >= 0; k -= 2) q.push(r.pts[k], r.pts[k + 1]); return q; })();
    out.push(...p.slice(2));
  }
  return out;
};
const midOf = (pts) => {               // the point halfway along a polyline
  const L = polyLen(pts); let acc = 0;
  for (let i = 0; i + 3 < pts.length; i += 2) { const sl = Math.hypot(pts[i + 2] - pts[i], pts[i + 3] - pts[i + 1]); if (acc + sl >= L / 2) { const t = (L / 2 - acc) / (sl || 1); return [r1(pts[i] + (pts[i + 2] - pts[i]) * t), r1(pts[i + 1] + (pts[i + 3] - pts[i + 1]) * t)]; } acc += sl; }
  return [pts[0], pts[1]];
};
const bearing = (pts) => { const dx = pts[pts.length - 2] - pts[0], dz = pts[pts.length - 1] - pts[1]; return Math.round(((Math.atan2(dx, -dz) * 180 / Math.PI) + 360) % 360 * 10) / 10; };   // degrees clockwise from north

/** metres of a polyline that lie inside the water union (sampled every 25 cm) */
const wetMetres = (pts, U) => {
  let wet = 0;
  for (let i = 0; i + 3 < pts.length; i += 2) {
    const sl = Math.hypot(pts[i + 2] - pts[i], pts[i + 3] - pts[i + 1]);
    for (let t = 0; t < sl; t += 0.25) if (inPolys(pts[i] + (pts[i + 2] - pts[i]) * t / sl, pts[i + 1] + (pts[i + 3] - pts[i + 1]) * t / sl, U)) wet += 0.25;
  }
  return Math.round(wet * 10) / 10;
};

/** a polyline against the water union: metres inside by more than 5 cm (wetM), metres inside within 5 cm of the outline (edgeM: the line IS the shore) and the deepest point */
const wetProfile = (pts, U) => {
  let wet = 0, edge = 0, max = 0;
  for (let i = 0; i + 3 < pts.length; i += 2) {
    const sl = Math.hypot(pts[i + 2] - pts[i], pts[i + 3] - pts[i + 1]);
    for (let t = 0; t < sl; t += 0.25) {
      const x = pts[i] + (pts[i + 2] - pts[i]) * t / sl, z = pts[i + 1] + (pts[i + 3] - pts[i + 1]) * t / sl;
      if (!inPolys(x, z, U)) continue;
      const d = Math.min(...U.flatMap((q) => [q.o, ...q.h]).map((r) => ringDist(x, z, r)));
      if (d > 0.05) wet += 0.25; else edge += 0.25;
      if (d > max) max = d;
    }
  }
  return { wetM: Math.round(wet * 10) / 10, edgeM: Math.round(edge * 10) / 10, maxDepthM: Math.round(max * 100) / 100 };
};

/** every module of the data folder as { 'water.js': text, ... } */
export function buildModules(d, union, F) {
  const U = union.polygons, st = union.stats;
  const decks = bridgeDecks(d.paths, U);
  const out = {};

  // ------------------------------------------------------------ water.js
  const lake = d.ponds.find((p) => p.id === LAKE_ID), west = d.ponds.find((p) => p.id === WEST_POND_ID);
  const strips = d.ponds.filter((p) => p.kind === 'canal-strip');
  const memorial = d.furniture.monuments.find((m) => m.sub === 'war_memorial');
  const islands = U.flatMap((p) => p.h).map((h) => {
    const b = bbox(h); const cx = r1((b.x0 + b.x1) / 2), cz = r1((b.z0 + b.z1) / 2);
    const area = Math.abs(polyArea({ o: h, h: [] }));
    let name = 'island-south', note = 'between the south canal arm w81524420 and the east arm w30198531';
    if (memorial && inRing(memorial.x, memorial.z, h)) { name = 'island-east'; note = `the big island round which the east arm w30198531 runs; the Pioneers-heroes memorial ${memorial.id} stands on it; reached by the iron bridge No.3`; }
    else if (area < 1000) { name = 'island-lake'; note = 'the island of the lake: the hole of the OSM relation r1582714 (wetland w188083936)'; }
    return { name, areaM2: Math.round(area), x0: r1(b.x0), x1: r1(b.x1), z0: r1(b.z0), z1: r1(b.z1), cx, cz, note, ring: h };
  }).sort((a, b) => b.areaM2 - a.areaM2);
  out['water.js'] = moduleText(head('water: the lake r1582714 and the west pond r6278222 (exact OSM outlines, the lake with its island hole), the four canals as centre lines with a width table, and the union of everything',
    [`Canal widths are ESTIMATED (provenance 'estimated', not surveyed): OSM maps the canals as centre lines only. The numbers (12 / 12 / 6 / 10 m) come from the source repository's generator, "estimated from aerial reference photographs and mapped bridge spans"; the width USED in the union (CANALS[].width) is the estimate lowered in ${CANAL_DRY_RULE.step} m steps until no mapped non-bridge garden way lies under the strip (CANALS[].estimate, wetAtEstimateM): the mapped footways are better evidence than the estimate.`,
      `Canal ends that OSM draws on a lake outline are moved ${CANAL_JOIN.overlap} m into it when the facade leaves them within ${CANAL_JOIN.tolerance} m (the facade is a simplified copy of the map): see CANALS[].joins. The union polygon is computed by tools/tauride/tauride-union.py (shapely ${union.shapely}, GEOS ${union.geos}), rounded to 1 mm, ring-cleaned and asserted valid.`]), {
    LAKE: { id: lake.id, o: lake.o, h: lake.h },
    WEST_POND: { id: west.id, o: west.o, h: west.h },
    CANALS: d.canals.map((c) => ({ id: c.id, width: c.width, estimate: c.estimate, provenance: c.provenance, lenM: c.len, joins: c.joins, pts: c.pts })),
    CANAL_WIDTH_TABLE: Object.fromEntries(d.canals.map((c) => [c.id, { width: c.width, estimate: c.estimate, ...(c.wetAtEstimateM !== undefined ? { wetAtEstimateM: c.wetAtEstimateM } : {}), provenance: c.provenance, note: CANAL_WIDTHS[c.id] ? CANAL_WIDTHS[c.id].note : '' }])),
    CANAL_STRIPS: strips.map((s) => ({ id: s.id, width: s.width, o: s.o })),
    WATER_UNION: U,
    WATER_ISLANDS: islands.map((i) => ({ name: i.name, areaM2: i.areaM2, x0: i.x0, x1: i.x1, z0: i.z0, z1: i.z1, cx: i.cx, cz: i.cz, note: i.note })),
    WATER_STATS: { netAreaM2: st.netAreaM2, shoreM: st.shoreM, polygons: st.polygons, holes: st.holes.length, pieces: st.pieces },
  }, ['CANAL_WIDTH_TABLE', 'WATER_STATS']);

  // ------------------------------------------------------------ bridges.js
  const byId = new Map(decks.map((b) => [b.id, b]));
  const sites = BRIDGE_SITES.map((s) => {
    const ways = s.ways.map((id) => byId.get(id));
    const deck = chainOf(ways);
    const ends = [[deck[0], deck[1]], [deck[deck.length - 2], deck[deck.length - 1]]];
    return {
      site: s.site, name: s.name, type: s.type, confidence: s.confidence, basis: s.basis, ways: s.ways, deckW: BRIDGE_DECK_WIDTH.value,
      centre: midOf(deck), bearingDeg: bearing(deck), deckLenM: r1(polyLen(deck)), wetSpanM: r1(ways.reduce((a, w) => a + w.wetSpanM, 0)),
      endsDry: !inPolys(ends[0][0], ends[0][1], U) && !inPolys(ends[1][0], ends[1][1], U), deck,
    };
  });
  const damWay = byId.get(DAM_WAY);
  const dc = midOf(damWay.pts);
  const dam = {
    way: DAM_WAY, authoritative: [dc[0], dc[1]], bearingDeg: bearing(damWay.pts), osmLenM: damWay.osmLenM, deckLenM: damWay.deckLenM, channelWidthM: r1(damWay.osmLenM + (damWay.ext[0] - BRIDGE_EXTEND.abutment) + (damWay.ext[1] - BRIDGE_EXTEND.abutment)),
    channelCanal: 'w112853212', mouthOnLake: [d.canals.find((c) => c.id === 'w112853212').pts.slice(-2)[0], d.canals.find((c) => c.id === 'w112853212').pts.slice(-1)[0]],
    rejected: { point: DAM_REJECTED.point, from: DAM_REJECTED.from, distM: r1(Math.hypot(dc[0] - DAM_REJECTED.point[0], dc[1] - DAM_REJECTED.point[1])), why: 'the west corner of the end cap of the 10 m strip that the source repository drew for canal w112853212 (end vertex (1273.8,-1655.1) minus half the 10 m width = 1268.8): an artefact of an ESTIMATED strip, not a mapped feature' },
    why: [`the only mapped structure on the channel between the west pond and the lake: OSM bridge=yes layer=1 without a surface tag (all seven other bridge ways name wood / metal / compacted), a ${damWay.osmLenM} m way across a channel that is about ${r1(damWay.osmLenM + (damWay.ext[0] - BRIDGE_EXTEND.abutment) + (damWay.ext[1] - BRIDGE_EXTEND.abutment))} m wide (estimated width)`,
      'it is the sixth crossing site: five numbered bridges + the dam; the plan\'s own camera "dam (1272,-1674)" stands 0.2 m from its centre',
      'the other point of the plan text lies 19.4 m away, in the middle of the estimated strip end; (1273.8,-1655.1) is where the canal centre line meets the lake outline (mouthOnLake), the natural place for the weir SILL if the water level steps there'].join('; '),
  };
  out['bridges.js'] = moduleText(head('the eight mapped bridge ways, grouped into the six crossing sites (five numbered bridges and the dam)',
    [`Mapping of OSM ways to the historical numbers: BRIDGE_SITES[].confidence 'plan' = the plan (section 5) gives the site, 'inferred' = by the order along the water, 'data' = from the geometry (the plan names no OSM way). DECK = the way after the old garden.js extension (a free end standing in the water moves along its axis until dry, +${BRIDGE_EXTEND.abutment} m of abutment): the bridge ends reach dry land.`,
      `deckW 3 m is a DESIGN value (the facade has 2.4 m = the highway=footway class default). wetSpanM = the metres of the OSM axis that lie inside the water union (derived).`]), {
    BRIDGE_DECK_WIDTH: BRIDGE_DECK_WIDTH,
    BRIDGE_SITES: sites,
    BRIDGE_WAYS: decks.map((b) => ({ id: b.id, site: BRIDGE_SITES.find((s) => s.ways.includes(b.id)).site, surface: b.surface, surfaceClass: b.surfaceClass, lit: b.lit, facadeW: b.facadeW, osmLenM: b.osmLenM, deckLenM: b.deckLenM, wetSpanM: b.wetSpanM, ext: b.ext, pts: b.pts, deck: b.deck })),
    DAM: dam,
  }, ['BRIDGE_DECK_WIDTH', 'DAM']);

  // ------------------------------------------------------------ paths.js
  const cls = {};
  for (const p of d.paths) { const c = cls[p.cls] || (cls[p.cls] = { count: 0, lenM: 0 }); c.count++; c.lenM += p.len; }
  for (const c of Object.values(cls)) c.lenM = Math.round(c.lenM);
  out['paths.js'] = moduleText(head('the garden ways of the OSM data (highway footway / path / pedestrian / steps with a vertex inside the garden polygon) with a width class',
    ['CLASS RULE (tools/tauride/lib/derive.mjs classOf; no OSM width tag exists on any of these ways, so the class is derived from highway, surface, lit, bridge and length): steps = highway steps; bridge = bridge yes; trail = highway path (1.4 m); main = footway and (length >= 150 m, or lit and length >= 30 m): width 3.5 + min(length, 300) / 300 m = 3.5 .. 4.5 m; side = every other footway (2.4 m).',
      `PATHS_IN_WATER lists the non-bridge ways that run through the water union: empty by construction, because the canal width USED is lowered until no mapped way lies under the strip (water.js CANALS[].estimate / wetAtEstimateM say what the estimate would have drowned). The class and width are a heuristic of this repository (a starting point the garden team may override in tools/tauride/lib/tables.mjs PATH_CLASS_OVERRIDES), not a survey. facadeW is the width the engine's streets module draws today (the class default of the facade). ${NOT_IN_LEGACY_TERRAIN.length} ways (NOT_IN_LEGACY_TERRAIN) are newer than the source repository's terrain.js (which had 118): all 118 old ids are present.`]), {
    PATH_CLASS_RULE,
    PATH_CLASS_OVERRIDES,
    PATH_CLASS_STATS: cls,
    PATHS_IN_WATER: d.paths.filter((p) => !p.bridge).map((p) => ({ id: p.id, cls: p.cls, lenM: p.len, wetM: wetMetres(p.pts, U) })).filter((p) => p.wetM > 0.5),
    NOT_IN_LEGACY_TERRAIN,
    LEGACY_PATH_COUNT: 118,
    PATHS: d.paths.map((p) => ({ id: p.id, hw: p.hw, cls: p.cls, w: p.w, lenM: p.len, surface: p.surface, surfaceClass: p.surfaceClass, lit: p.lit, bridge: p.bridge, layer: p.layer, ...(p.steps ? { steps: p.steps } : {}), facadeW: p.facadeW, pts: p.pts })),
  }, ['PATH_CLASS_RULE', 'PATH_CLASS_OVERRIDES', 'PATH_CLASS_STATS']);

  // ------------------------------------------------------------ furniture.js
  const fu = d.furniture, fenceLen = d.barriers.reduce((s, f) => s + f.len, 0);
  out['furniture.js'] = moduleText(head('furniture, trees, monuments, fences and gates of the garden',
    [`Ids are the OSM ids of the facade records (props/osm.js draws every FURNITURE bench / waste_basket node today: the remake claims them by id). FENCE_OPENINGS reproduce the rule of the old garden.js (a 2.7 m panel is left out within ${FENCE_RULES.gateClear} m of a gate node or ${FENCE_RULES.pathClear} m of a path); FENCES_IN_WATER: fence ways that coincide with the water outline (edgeM, the fence IS the shore: the north shore of the lake) or stand in the water (wetM, maxDepthM). FENCE_GAPS are stretches of the garden outline longer than ${FENCE_RULES.gapMin} m with no mapped fence within ${FENCE_RULES.perimeterNear} m.`,
      'CARS: the mapped fence is open at FENCE_OPENINGS (gate-only and path crossings) and at FENCE_GAPS, and SERVICE_LANE runs into the garden from the west gate: a car keep-out POLYGON (the garden outline, see footprints.js GARDEN), not gate bollards, is what keeps cars out.']), {
    BENCHES: fu.benches,
    BINS: fu.bins,
    OTHER_FURNITURE: fu.other,
    FOUNTAINS: fu.fountains,
    OSM_TREES: fu.trees,
    MONUMENTS: fu.monuments,
    LAMPS_IN_GARDEN: fu.lamps,
    FENCES: d.barriers.map((f) => ({ id: f.id, closed: f.closed, lenM: f.len, pts: f.pts })),
    FENCE_STATS: { ways: d.barriers.length, lenM: Math.round(fenceLen), panelM: FENCE_RULES.panel, panels: Math.round(d.barriers.reduce((s, f) => s + Math.ceil(f.len / FENCE_RULES.panel), 0)), perimeterM: d.unfenced.perimeterM, perimeterFencedM: d.unfenced.coveredM },
    FENCES_IN_WATER: d.barriers.map((f) => ({ id: f.id, ...wetProfile(f.pts, U) })).filter((f) => f.wetM > 0.5 || f.edgeM > 0.5),
    FENCE_OPENINGS: d.openings,
    FENCE_GAPS: d.unfenced.gaps,
    GATES: d.gates,
    SERVICE_LANE: d.serviceLane,
  }, ['FENCE_STATS', 'SERVICE_LANE']);

  // ------------------------------------------------------------ footprints.js
  out['footprints.js'] = moduleText(head('the garden outline, the GREEN records it holds and the building footprints that overlap it (hills, trees and paths must keep out of them)',
    [`FOOTPRINTS: every building outline or part (not the palace, which lies outside the outline) whose footprint overlaps the garden polygon by more than 1 m2 (grid sampling, 0.25 m): ${d.footprints.length} records. HILL_KEEP_OUT_MARGIN is a design value.`]), {
    GARDEN: { id: d.gardenId, name: d.gardenName, areaM2: Math.round(polyArea(d.garden[0])), o: d.garden[0].o, h: d.garden[0].h },
    GARDEN_GREEN: d.green,
    HILL_KEEP_OUT_MARGIN: 3,
    FOOTPRINTS: d.footprints.map((f) => ({ id: f.id, kind: f.kind, name: f.name, part: f.part, parent: f.parent, h: f.h, levels: f.levels, areaM2: f.areaM2, overlapM2: Math.min(f.overlapM2, f.areaM2), polys: f.polys })),
  }, ['GARDEN_GREEN']);
  return out;
}
