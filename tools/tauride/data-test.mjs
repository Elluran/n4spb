const fur = new Map(F.FURNITURE.map((f) => [f.id, f]));
eq(Fu.BENCHES.length, 132, 'benches');
eq(Fu.BINS.length, 167, 'waste baskets');
ok(Fu.BENCHES.every((b) => fur.get(b.id) && fur.get(b.id).kind === 'bench' && fur.get(b.id).x === b.x && fur.get(b.id).z === b.z), 'every bench id is a facade FURNITURE bench at the same place');
ok(Fu.BINS.every((b) => fur.get(b.id) && fur.get(b.id).kind === 'waste_basket' && fur.get(b.id).x === b.x && fur.get(b.id).z === b.z), 'every bin id is a facade FURNITURE waste_basket at the same place');
eq(Fu.OTHER_FURNITURE.length, 6, 'other furniture (picnic table 1, bicycle rental 1, bicycle parking 4)');
ok(Fu.OTHER_FURNITURE.every((o) => fur.has(o.id)), 'other furniture ids exist');
eq(Fu.FOUNTAINS.length, 1, 'fountain');
ok(Fu.FOUNTAINS[0].id === 'n950150577' && fur.has('n950150577'), 'the fountain "Boy with a duck" n950150577');
eq(Fu.BENCHES.length + Fu.BINS.length + Fu.OTHER_FURNITURE.length + Fu.FOUNTAINS.length, 306, 'FURNITURE records in the garden (scout: 306)');
eq(Fu.OSM_TREES.length, 7, 'OSM tree nodes');
ok(Fu.OSM_TREES.every((t) => { for (let i = 0; i < F.TREES.length; i += 2) if (F.TREES[i] === t.x && F.TREES[i + 1] === t.z) return true; return false; }), 'every OSM tree is a facade TREES point');
eq(Fu.MONUMENTS.length, 3, 'monuments (Chaikovsky, Esenin, Pioneers-heroes)');
