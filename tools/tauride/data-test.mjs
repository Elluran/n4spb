ok(U.every((p) => p.h.every((h) => !ringsCross(p.o, h) && h.every((v, i) => i % 2 || inRing(v, h[i + 1] === undefined ? 0 : h[i + 1], p.o) || ringDist(v, h[i + 1], p.o) < 0.01))), 'holes lie inside the outer ring and do not cross it');
