ok(jsonEq(water.get('r6278222').polys[0].o, W.WEST_POND.o), 'west pond r6278222 = facade WATER');
eq(W.LAKE.h.length, 1, 'the lake has one island hole');
eq(W.CANALS.length, 4, 'canals');
ok(W.CANALS.every((c) => stream.has(c.id) && stream.get(c.id).kind === 'canal' && jsonEq(stream.get(c.id).pts, c.pts)), 'canal centre lines = facade STREAMS');
