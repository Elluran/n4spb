ok(['w30198531:12', 'w81524420:12', 'w112853192:6', 'w112853212:10'].every((e) => W.CANAL_WIDTH_TABLE[e.split(':')[0]].estimate === Number(e.split(':')[1])), 'the estimates are those of the source repository (12 / 12 / 6 / 10)');
eq(W.CANAL_STRIPS.length, 4, 'canal strips');
const U = W.WATER_UNION;
