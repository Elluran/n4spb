// Check of the Tauride Garden data modules (src/world/landmarksTauride/data/*.js) against the North facade and against the numbers of the scout report (D:/git2/n4spb-work/tauride-source-map.json,
// docs/TAURIDE-REMAKE.md section 5): every id exists in the facade and carries the same geometry, the counts are the documented ones, the water union is one valid watertight outline that holds both OSM
// outlines and every canal centre line, the garden items are dry, the bridge ends reach dry land, and the pipeline is deterministic (run twice: byte-identical; and identical to the committed files).
//   node tools/tauride/data-test.mjs [--no-regen]
// --no-regen skips the pipeline runs (the only steps that need Python + shapely); they are reported as SKIPPED, never as passed.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { ROOT, TAURIDE_DIR, DATA_DIR, parseArgs, loadFacade, shapelyInfo, inRing, inPoly, inPolys, ringDist, selfIntersects, ringsCross, polyLen, polyArea, ringArea, rel } from './lib/common.mjs';
import { classOf, widthOf } from './lib/derive.mjs';
import { NOT_IN_LEGACY_TERRAIN } from './lib/emit.mjs';
import { CANAL_WIDTHS, PATH_CLASS_RULE } from './lib/tables.mjs';

const args = parseArgs();
let fails = 0, checks = 0;
const ok = (cond, name, detail = '') => { checks++; if (!cond) fails++; console.log(`${cond ? 'ok  ' : 'FAIL'} ${name}${detail ? ' :: ' + detail : ''}`); return cond; };
const eq = (a, b, name) => ok(a === b, name, `${a} vs ${b}`);
const near = (a, b, tol, name) => ok(Math.abs(a - b) <= tol, name, `${a} vs ${b} (+-${tol})`);
const jsonEq = (a, b) => JSON.stringify(a) === JSON.stringify(b);

const F = await loadFacade();
const mod = async (n) => import(pathToFileURL(path.join(DATA_DIR, n + '.js')).href);
const W = await mod('water'), B = await mod('bridges'), P = await mod('paths'), Fu = await mod('furniture'), Fo = await mod('footprints');

console.log('== files');
for (const n of ['water', 'bridges', 'paths', 'furniture', 'footprints']) {
  const f = path.join(DATA_DIR, n + '.js'), buf = fs.readFileSync(f), txt = buf.toString('utf8');
  ok(!(buf[0] === 0xef && buf[1] === 0xbb), `${n}.js has no BOM`);
  ok(!txt.includes('\r'), `${n}.js uses LF`);
  ok(!/^\s*import\s/m.test(txt) && !/\bimport\(/.test(txt), `${n}.js is pure data (no import)`);
  ok(/GENERATED by node tools\/tauride\/build\.mjs/.test(txt) && /ODbL/.test(txt) && /OpenStreetMap contributors/.test(txt), `${n}.js header names the tool, the source and the licence`);
  ok(Buffer.byteLength(txt) < 40000, `${n}.js is small`, `${Buffer.byteLength(txt)} B`);
}

console.log('== ids and geometry against the facade');
const road = new Map(F.ROADS.map((r) => [r.id, r]));
ok(P.PATHS.every((p) => road.has(p.id)), 'every garden way id is a facade ROADS record');
ok(P.PATHS.every((p) => jsonEq(road.get(p.id).pts, p.pts)), 'every garden way has the facade geometry');
ok(P.PATHS.every((p) => (road.get(p.id).bridge ? 1 : 0) === p.bridge && (road.get(p.id).surface || null) === p.surface && (road.get(p.id).lit ? 1 : 0) === p.lit), 'surface, lit and bridge flags equal the facade');
eq(P.PATHS.length, 120, 'garden ways in the facade (118 of the source terrain.js + 2 newer)');
eq(P.PATHS.length - P.NOT_IN_LEGACY_TERRAIN.length, P.LEGACY_PATH_COUNT, 'the 118 legacy ways are all present');
ok(P.NOT_IN_LEGACY_TERRAIN.every((id) => road.has(id)) && jsonEq(P.NOT_IN_LEGACY_TERRAIN, NOT_IN_LEGACY_TERRAIN), 'the two newer ways (w425188838, w425188839) exist');
eq(new Set(P.PATHS.map((p) => p.id)).size, P.PATHS.length, 'no duplicate way id');
eq(P.PATHS.filter((p) => p.bridge).length, 8, 'bridge ways (OSM bridge=yes)');
const gardenRing = Fo.GARDEN.o;
ok(jsonEq(F.GREEN.find((g) => g.id === 'r1582734').polys[0].o, gardenRing), 'garden outline = GREEN r1582734 of the facade');
ok(P.PATHS.every((p) => p.pts.some((v, i) => i % 2 === 0 && inRing(v, p.pts[i + 1], gardenRing))), 'every garden way has a vertex in the garden outline');
const sums = Object.values(P.PATH_CLASS_STATS).reduce((s, c) => s + c.count, 0);
eq(sums, P.PATHS.length, 'class counts add up');
ok(P.PATHS.every((p) => ['main', 'side', 'trail', 'steps', 'bridge'].includes(p.cls)), 'every way has a class');
ok(P.PATHS.every((p) => p.cls === classOf({ id: p.id, hw: p.hw, bridge: p.bridge, lit: p.lit }, polyLen(p.pts))), 'the stored class is what the documented rule gives');
ok(P.PATHS.every((p) => Math.abs(p.w - widthOf(p.cls, polyLen(p.pts), { w: p.facadeW })) < 1e-9), 'the stored width is what the documented rule gives');
ok(P.PATHS.filter((p) => p.cls === 'main').every((p) => p.w >= PATH_CLASS_RULE.main.wMin && p.w <= PATH_CLASS_RULE.main.wMax), 'main alleys are 3.5 .. 4.5 m');
ok(P.PATHS.filter((p) => p.cls === 'trail').every((p) => p.w === 1.4) && P.PATHS.filter((p) => p.cls === 'side').every((p) => p.w === 2.4), 'trails 1.4 m, side ways 2.4 m');
eq(P.PATHS.filter((p) => p.hw === 'steps').length, 6, 'steps ways');
eq(P.PATHS.filter((p) => p.lit).length, 17, 'lit ways (16 land + 1 bridge)');
ok(P.PATHS.filter((p) => p.cls === 'main').length >= 15, 'main alleys', String(P.PATHS.filter((p) => p.cls === 'main').length));
near(P.PATHS.filter((p) => !p.bridge && !P.NOT_IN_LEGACY_TERRAIN.includes(p.id)).reduce((s, p) => s + polyLen(p.pts), 0), 8995, 3, 'length of the 110 legacy non-bridge ways (scout: 8,995 m)');

const barrier = new Map(F.BARRIERS.map((b) => [b.id, b])), bnode = new Map(F.BARRIER_NODES.map((b) => [b.id, b]));
eq(Fu.FENCES.length, 14, 'fence ways');
ok(Fu.FENCES.every((f) => barrier.has(f.id) && barrier.get(f.id).kind === 'fence'), 'every fence id is a facade BARRIERS fence');
