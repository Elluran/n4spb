console.log('== determinism');
const info = shapelyInfo();
if (args['no-regen'] || !info.ok) {
  console.log(`SKIPPED regenerate-twice and compare-with-committed: ${args['no-regen'] ? '--no-regen' : info.why}`);
} else {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tauride-'));
  const run = (tag) => {
    const out = path.join(tmp, tag, 'data'), work = path.join(tmp, tag, 'work');
    const r = spawnSync(process.execPath, [path.join(TAURIDE_DIR, 'build.mjs'), '--out', out, '--work', work], { encoding: 'utf8', cwd: ROOT, env: { ...process.env, NODE_OPTIONS: process.env.NODE_OPTIONS || '--max-old-space-size=4000' } });
    if (r.status !== 0) { console.log(r.stdout + r.stderr); return null; }
    return Object.fromEntries(fs.readdirSync(out).sort().map((f) => [f, fs.readFileSync(path.join(out, f))]));
  };
  const a = run('a'), b = run('b');
  if (ok(a && b, 'the generator runs twice')) {
    ok(Object.keys(a).join() === Object.keys(b).join() && Object.keys(a).every((k) => a[k].equals(b[k])), 'two runs are byte-identical', Object.keys(a).map((k) => k + ':' + a[k].length).join(' '));
    ok(Object.keys(a).every((k) => fs.existsSync(path.join(DATA_DIR, k)) && fs.readFileSync(path.join(DATA_DIR, k)).equals(a[k])), 'and byte-identical to the committed modules');
  }
  fs.rmSync(tmp, { recursive: true, force: true });
}
console.log(`\n${checks} checks, ${fails} failed`);
console.log(fails ? 'RESULT: FAIL' : 'RESULT: OK');
process.exit(fails ? 1 : 0);
