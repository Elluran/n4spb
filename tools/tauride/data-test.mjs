ok(U.every((p) => ringArea(p.o) !== 0 && p.h.every((h) => ringArea(h) !== 0)), 'no degenerate ring');
const inUnionOrEdge = (x, z) => inPolys(x, z, U) || U.some((p) => ringDist(x, z, p.o) < 0.01 || p.h.some((h) => ringDist(x, z, h) < 0.01));
ok(W.LAKE.o.every((v, i) => i % 2 || inUnionOrEdge(v, W.LAKE.o[i + 1])), 'the union contains every vertex of the lake outline');
ok(W.WEST_POND.o.every((v, i) => i % 2 || inUnionOrEdge(v, W.WEST_POND.o[i + 1])), 'the union contains every vertex of the west pond outline');
ok(W.CANALS.every((c) => c.pts.every((v, i) => i % 2 || inUnionOrEdge(v, c.pts[i + 1]))), 'the union contains every canal centre line vertex');
ok(W.CANAL_STRIPS.every((s) => s.o.every((v, i) => i % 2 || inUnionOrEdge(v, s.o[i + 1]))), 'the union contains every canal strip');
ok(W.LAKE.h.every((h) => h.every((v, i) => i % 2 || U[0].h.some((uh) => inRing(v, h[i + 1], uh) || ringDist(v, h[i + 1], uh) < 0.01))), 'the lake island hole lies in a union hole');
ok(F.GREEN.filter((g) => g.id === 'w188083936').every((g) => inRing(g.polys[0].o[0], g.polys[0].o[1], U[0].h.find((h) => inRing(1378.8, -1575.2, h)) || [])), 'the wetland w188083936 (lake island) is a union hole');
ok(W.WATER_ISLANDS.length === 3 && W.WATER_ISLANDS.map((i) => i.name).sort().join() === 'island-east,island-lake,island-south', 'islands named east / south / lake');
const mem = Fu.MONUMENTS.find((m) => m.id === 'n4186236011');
