function ringOf(b) { const o = b.polys[0].o, r = []; for (let i = 0; i + 1 < o.length; i += 2) r.push([o[i], o[i + 1]]); if (r.length > 1 && r[0][0] === r[r.length - 1][0] && r[0][1] === r[r.length - 1][1]) r.pop(); return r; }
function inRing(r, x, z) { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, zi] = r[i], [xj, zj] = r[j]; if ((zi > z) !== (zj > z) && x < (xj - xi) * (z - zi) / (zj - zi) + xi) c = !c; } return c; }
function segDist(px, pz, ax, az, bx, bz) { const dx = bx - ax, dz = bz - az, l2 = dx * dx + dz * dz || 1; let t = ((px - ax) * dx + (pz - az) * dz) / l2; t = Math.max(0, Math.min(1, t)); return Math.hypot(px - (ax + t * dx), pz - (az + t * dz)); }
function ringGap(r1, r2) {
  let m = 1e9;
  for (const [px, pz] of r1) for (let j = 0; j < r2.length; j++) { const [ax, az] = r2[j], [bx, bz] = r2[(j + 1) % r2.length]; m = Math.min(m, segDist(px, pz, ax, az, bx, bz)); }
  for (const [px, pz] of r2) for (let j = 0; j < r1.length; j++) { const [ax, az] = r1[j], [bx, bz] = r1[(j + 1) % r1.length]; m = Math.min(m, segDist(px, pz, ax, az, bx, bz)); }
  return m;
}
function obbOf(r) {
  let best = null;
  for (let i = 0; i < r.length; i++) {
    const a = r[i], b = r[(i + 1) % r.length], dx = b[0] - a[0], dz = b[1] - a[1], l = Math.hypot(dx, dz) || 1, ux = dx / l, uz = dz / l;
    let u0 = 1e9, u1 = -1e9, v0 = 1e9, v1 = -1e9;
    for (const p of r) { const u = (p[0] - a[0]) * ux + (p[1] - a[1]) * uz, v = -(p[0] - a[0]) * uz + (p[1] - a[1]) * ux; u0 = Math.min(u0, u); u1 = Math.max(u1, u); v0 = Math.min(v0, v); v1 = Math.max(v1, v); }
    const A = (u1 - u0) * (v1 - v0);
    if (!best || A < best.A) best = { A, w: Math.max(u1 - u0, v1 - v0), d: Math.min(u1 - u0, v1 - v0) };
  }
  return best;
}

