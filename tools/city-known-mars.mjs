function archFor(it, f, pf, annex) {
  const { row, b, obb } = it, id = it.id, h = hash01(id + 'arch');
  const tag = (b.tags && b.tags['building:architecture']) || '';
  const sd = parseInt(b.startDate || row.osmTags?.start_date || '', 10) || 0;
  const kind = b.kind || '';
  if (it.area < 60) return 'SERVICE';
  if (annex && f <= 2 && it.area < 450) return it.area < 100 ? 'SERVICE' : 'COURT';
  if (pf.kind === 'court') return f <= 1 && it.area < 300 ? 'SERVICE' : 'COURT';
  if (tag === 'modern' || /^(2009|201|202)/.test(String(b.startDate || ''))) return 'MODERN';
  if (/neoclass/.test(tag)) return f >= 5 ? 'NEOCLASS' : 'CLASSIC';
  if (sd && sd < 1850) return f <= 4 ? 'CLASSIC' : 'ECLECTIC';
  if (sd >= 1890 && sd < 1918) return f >= 4 ? (h < 0.5 ? 'NOUVEAU' : 'TENEMENT') : 'ECLECTIC';
  if (sd >= 1930 && sd < 1990) return 'STALIN';
  if (kind === 'kindergarten' && f <= 2) return 'COURT';
  if (pf.kind === 'palace' || pf.kind === 'mansion') return f <= 3 ? (h < 0.72 ? 'CLASSIC' : 'ECLECTIC') : (f === 4 ? (h < 0.6 ? 'ECLECTIC' : 'CLASSIC') : (h < 0.6 ? 'ECLECTIC' : 'TENEMENT'));
  if (pf.kind === 'late') {
    if (f <= 2) return 'CLASSIC';
    if (f === 3) return h < 0.5 ? 'CLASSIC' : 'ECLECTIC';
    if (f === 4) return h < 0.46 ? 'ECLECTIC' : h < 0.72 ? 'TENEMENT' : h < 0.88 ? 'CLASSIC' : 'NOUVEAU';
    return h < 0.34 ? 'TENEMENT' : h < 0.62 ? 'ECLECTIC' : h < 0.9 ? 'NOUVEAU' : 'BRICK';
  }
  // core (Millionnaya / Moika / Gagarinskaya ...): plain classicism and eclectic stucco
  if (f <= 2) return 'CLASSIC';
  if (f === 3) return h < 0.62 ? 'CLASSIC' : 'ECLECTIC';
  if (f === 4) return h < 0.5 ? 'ECLECTIC' : h < 0.82 ? 'CLASSIC' : 'TENEMENT';
  return h < 0.5 ? 'ECLECTIC' : h < 0.8 ? 'TENEMENT' : 'NOUVEAU';
}
