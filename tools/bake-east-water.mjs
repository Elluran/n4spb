// Bake the complete eastern Neva bend as scenery beyond the walkable district.
// The normal city bake clips water at PLAY+120m, halfway across this wide river.
// Source: the same Overpass water.json; OSM contributors, ODbL.
import fs from 'node:fs';
import { elementPolys, clipRing, flat, simplify, bboxOf } from './osm-lib.mjs';
const root = new URL('../', import.meta.url);
const raw = JSON.parse(fs.readFileSync(new URL('data/osm-raw/water.json', root), 'utf8'));
export const box = { x0: -3500, x1: 5200, z0: -3400, z1: 4600 };
const waters = [];
for (const e of raw.elements) {
  if (!['Нева', 'Большая Нева', 'Монастырка', 'Обводный канал'].includes(e.tags?.name) && e.id !== 3298178) continue;
  for (const p of elementPolys(e)) {
    const o = clipRing(p.o, box);
    if (!o) continue;
    waters.push({ id: e.type[0] + e.id, name: e.tags.name || 'Монастырка', box: bboxOf(o), o: flat(simplify(o, 0.15)), h: p.h.map(h => clipRing(h, box)).filter(Boolean).map(h => flat(simplify(h, 0.15))) });
  }
}
if (!waters.some(p => p.name === 'Нева')) throw new Error('Missing Neva polygon');
fs.writeFileSync(new URL('src/world/data/east-water.js', root), '// GENERATED by tools/bake-east-water.mjs. OpenStreetMap contributors, ODbL.\nexport const EAST_WATER_BOUNDS = ' + JSON.stringify(box) + ';\nexport const EAST_WATER = ' + JSON.stringify(waters) + ';\n');
console.log('Eastern water polygons:', waters.length);
