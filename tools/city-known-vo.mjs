// city-known-vo.mjs - KNOWN houses of VASILIEVSKY ISLAND: writes the merged table docs/research/vo-houses.json and appends a generated block (marker VO) to src/world/city/known-data.js
//   from the 82 ordinary houses of the architecture roster (docs/research/vo-roster-architecture.md section 8), the houses tables of the 16 sight dossiers
//   (docs/research/<slug>-houses.json: academy menshikov mining andrew navalcorps smolensky seaterminal sevkabel kirova makarova sredny gavan pribaltiyskaya marinefacade modernvo oktyabrsky)
//   and the hand-written records of tools/city-known-vo-curated.mjs; OSM footprints of src/world/data/city.js; claims of layout.GROUPS.
// usage: node tools/city-known-vo.mjs [--dry] [--print] [--list]
//   (default) writes docs/research/vo-houses.json and the block between the VO markers at the end of known-data.js (the other generators keep foreign blocks when they regenerate theirs)
//   --dry  report only      --print  one line per generated entry      --list  the claimed / placeholder / unmatched rows
// The rules are those of tools/city-known-petro.mjs (same row -> entry conversion), with these differences:
//   * the roster rows of section 8 are parsed from the markdown table (colours tagged `v` = read off an opened photo give `hex`; `e` = estimate: the district palette decides at run time);
//   * a row whose OSM id (or parent) is claimed by a landmark module (layout.GROUPS: bol18, pel16, akad2, gor47, the ModernVO hero houses, the October group ...) is SKIPPED and listed: the module draws it;
//   * rows without research (conf L, no style / wall / year / features) are skipped: the island grammar (city/district.js voZoneOf / VO_MIX) decides;
//   * a house in several tables: the better-researched row wins (H > M > L), curated records win over rows.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const TABLES = ['academy', 'menshikov', 'mining', 'andrew', 'navalcorps', 'smolensky', 'seaterminal', 'sevkabel', 'kirova', 'makarova', 'sredny', 'gavan', 'pribaltiyskaya', 'marinefacade', 'modernvo', 'oktyabrsky'];
const { CURATED } = await import(pathToFileURL(path.join(root, 'tools/city-known-vo-curated.mjs')).href);
const D = await import(pathToFileURL(path.join(root, 'src/world/data/city.js')).href);
const L = await import(pathToFileURL(path.join(root, 'src/world/layout.js')).href);
const KD_FILE = path.join(root, 'src/world/city/known-data.js');
const OUT_JSON = path.join(root, 'docs/research/vo-houses.json');
const BEGIN = '// ---- BEGIN VO (generated by tools/city-known-vo.mjs: do not edit by hand) ----', BEGIN_RE = /\/\/ ---- BEGIN VO /, END = '// ---- END VO ----';
const byId = new Map(D.BUILDINGS.map((b) => [b.id, b]));
const RANK = { H: 3, M: 2, L: 1 };

const hexIn = (s) => { const m = /#[0-9a-fA-F]{6}\b/.exec(typeof s === 'string' ? s : ''); return m ? m[0].toLowerCase() : null; };
const rgb = (h) => { const v = parseInt(h.slice(1), 16); return [v >> 16, (v >> 8) & 255, v & 255]; };
const cdist = (a, b) => { const p = rgb(a), q = rgb(b); return Math.hypot(p[0] - q[0], p[1] - q[1], p[2] - q[2]) / 441; };
const lum = (h) => { const [r, g, b] = rgb(h); return (0.299 * r + 0.587 * g + 0.114 * b) / 255; };
const hash01 = (s) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } h ^= h >>> 15; h = Math.imul(h, 2246822519); h ^= h >>> 13; return (h >>> 0) / 4294967296; };
function inRing(o, x, z) { let c = false; for (let i = 0, j = o.length - 2; i < o.length; j = i, i += 2) { const xi = o[i], zi = o[i + 1], xj = o[j], zj = o[j + 1]; if ((zi > z) !== (zj > z) && x < (xj - xi) * (z - zi) / (zj - zi) + xi) c = !c; } return c; }
function trimClassOf(trimS, wall) {
  const th = hexIn(trimS);
  if (!th || !wall) return undefined;
  if (cdist(th, wall) < 0.07) return 2;
  if (lum(th) < 0.62) return 5;
  if (lum(th) < 0.80) return 4;
  const [r, , b] = rgb(th);
  return r - b > 28 ? 3 : 1;
}

// ---------------------------------------------------------------- style -> archetype (as city-known-petro.mjs)
const CLASS = { classic: 'CLASSIC', eclectic: 'ECLECTIC', nouveau: 'NORDIC', nordic: 'NORDIC', neoclassic: 'NEOCLASSIC1910', stalin: 'STALIN', constructivism: 'PANEL', modern: 'MODERN' };
function archOf(row, f, year, feat, area) {
  const cls = CLASS[String(row.style || '').toLowerCase()];
  const s = (String(row.style || '') + ' ' + String(row.era || '')).toLowerCase();
  let a = cls || null;
  if (!a) {
    if (/сталин|stalin/.test(s)) a = 'STALIN';
    else if (/constructiv|конструктив/.test(s)) a = 'PANEL';
    else if (/советск|soviet|panel|196\d|197\d|198\d/.test(s)) a = 'PANEL';
    else if (/\bshed\b|\bsheds\b|\bboiler|\bgarage|\bfrigate|сарай|котельн|гараж|фрегат/.test(String(row.style || '').toLowerCase())) a = 'SERVICE';
    else if (/стилизац|20[012]\d|new building|new residential|modern infill|business centre|business center|бизнес|современн|офисн/.test(s)) a = 'MODERN';
    else if (/northern modern|северный модерн|art nouveau|модерн(?![а-яё])|jugend/.test(s)) a = 'NORDIC';
    else if (/neoclassic|неокласси/.test(s)) a = 'NEOCLASSIC1910';
    else if (/кирпичн|brick/.test(s)) a = 'BRICK';
    else if (/mansion|особняк/.test(s)) a = f <= 3 ? 'MANSION' : 'ECLECTIC';
    else if (/baroque|барокко|petrine|trezzini/.test(s) && year && year < 1800) a = 'CLASSIC';
    else if (/eclectic|эклект|renaissance|baroque|барокко|historicism|tenement/.test(s)) a = 'ECLECTIC';
    else if (/classic|класси|empire|ампир|pavilion of|leblon/.test(s)) a = 'CLASSIC';
    else if (/service|yard|courtyard|^plain |book stack|флигел|служебн|wing|annex/.test(s)) a = f <= 1 && area < 300 ? 'SERVICE' : 'COURT';
  }
  if (!a && year) {                                                // no style word: the era of the last building phase before 1918 gives the class (roster rows, plain dated rows)
    if (year < 1850) a = f >= 5 ? 'ECLECTIC' : 'CLASSIC';
    else if (year < 1895) a = 'ECLECTIC';
    else if (year < 1910) a = f >= 4 ? 'NORDIC' : 'ECLECTIC';
    else if (year <= 1917) a = f >= 5 ? (/neo-?baroque|neoclass/.test(s) ? 'NEOCLASSIC1910' : 'NORDIC') : 'ECLECTIC';
  }
  if (!a) return null;
  if (a === 'NORDIC' && f < 3) a = 'ECLECTIC';
  if (a === 'NEOCLASSIC1910' && f < 4) a = 'CLASSIC';
  if (a === 'CLASSIC' && f >= 5 && !(year && year < 1860)) a = 'ECLECTIC';
  if (a === 'ECLECTIC') {
    if (f <= 2 && /mansion|особняк/.test(feat + ' ' + s)) a = 'MANSION';
    else if (f >= 5 && year >= 1895 && (/bay|erker|эркер|tower|башн/.test(feat) || hash01(row.osm + 'ten') < 0.4)) a = 'TENEMENT';
  }
  return a;
}
const yearOf = (row) => { const all = (String(row.year || row.era || '').match(/(1[6-9]\d\d|20[0-2]\d)/g) || []).map(Number); if (!all.length) return 0; const old = all.filter((y) => y <= 1917); return old.length ? Math.max(...old) : all[0]; };
function featuresOf(row, a, f) {
  const t = (String(row.features || '') + ' ' + String(row.notes || '') + ' ' + String(row.roof || '') + ' ' + (CLASS[String(row.style || '').toLowerCase()] ? '' : String(row.style || ''))).toLowerCase();
  const e = {};
  const bay = /bay window|bay windows|erker|эркер|bay turret|tower bay|corner bay|rounded corner bay|oriel/.test(t);
  const lost = /tower[^.;]{0,30}(is |are )?lost|lost[^.;]{0,30}(tower|tent|dome)|утрачен|dome[^.;]{0,20}(is )?lost/.test(t);
  if (a === 'NORDIC' || a === 'TENEMENT' || a === 'ECLECTIC' || a === 'NEOCLASSIC1910') { if (bay) e.er = 1; }
  if (/turret|corner tower|round corner tower|round tower|towers|башн|clock tower|belvedere|cupola|lantern|dome/.test(t) && !(lost && !/towers in the middle/.test(t)) && a !== 'SERVICE' && a !== 'COURT' && a !== 'MODERN' && a !== 'PANEL' && a !== 'STALIN') {
    e.tu = 1;
    e.tt = /spire|шпил|needle/.test(t) ? 'spire' : /tent|шатр|pyramid|conical|cone/.test(t) ? 'tent' : /dome|cupola|купол|onion|lantern/.test(t) ? (a === 'NORDIC' ? 'helm' : 'dome') : a === 'NORDIC' ? 'helm' : undefined;
    if (!e.tt) delete e.tt;
  }
  if (a === 'NORDIC') {
    if (/stepped attic|stepped gable/.test(t)) { e.gb = 2; e.gs = 3; }
    else if (/horseshoe|round gable|semicircular gable/.test(t)) { e.gb = 1; e.gs = 0; }
    else if (/baroque gable|shaped gable|curved gable|wavy|curvilinear|scrolled gable/.test(t)) { e.gb = 1; e.gs = 1; }
    else if (/twin gable|steep gable|gothic/.test(t)) { e.gb = 2; e.gs = 2; }
    else if (/gable|щипц|аттик/.test(t)) e.gb = 1;
    if (/majolica|tile cladding|glazed tile|glazed ceramics|ceramic|майолик|изразц|tile band|tile frieze|tile panels/.test(t)) e.mj = 1;
    e.so = /rough granite|rough-hewn|granite floors|dark granite/.test(String(row.socle || '') + ' ' + t) || String(row.style).toLowerCase() === 'nordic' ? 1 : 0;
  }
  if (/majolica panels|glazed ceramics/.test(t) && a !== 'NORDIC') e.rich = 1;
  if (/mansard|мансард|dormer/.test(t)) e.ms = 1;
  if (a === 'NEOCLASSIC1910' || a === 'STALIN' || a === 'CLASSIC') {
    if (/balustrade|балюстрад/.test(t)) e.pp = 'bal'; else if (/\battic\b|аттик/.test(t)) e.pp = 'attic';
    if (/half-column|columns|колонн|colonnade/.test(t)) e.col = 1;
    if (/pilaster|relief|пилястр|рельеф|garland|medallion/.test(t)) e.rich = 1;
  }
  if (/two-storey mansion|set back behind a garden|school|училищ|школ|institute|институт|museum|музей|hospital|больниц|palace|дворец|academy|академи|depot|депо|barrack|казарм|laborator|лаборатор|pavilion|dormitory|общежити|university|library|church|police|fire station|kindergarten|clinic|court house|courthouse|nursery|market hall/.test(t + ' ' + String(row.name || '').toLowerCase() + ' ' + String(row.style || '').toLowerCase())) e.shop = false;
  void f;
  return e;
}

// ---------------------------------------------------------------- the roster table (section 8 of vo-roster-architecture.md)
function rosterRows() {
  const md = fs.readFileSync(path.join(root, 'docs/research/vo-roster-architecture.md'), 'utf8').split(/\r?\n/);
  const out = [];
  let on = false;
  for (const line of md) {
    if (/^## 8\. The roster/.test(line)) { on = true; continue; }
    if (on && /^### 8\.2/.test(line)) break;
    if (!on || !line.startsWith('|')) continue;
    const c = line.split('|').slice(1, -1).map((s) => s.trim());
    if (c.length < 13 || !/^[wr]\d+$/.test(c[3])) continue;
    const xz = c[4].split(',').map((s) => Number(s.trim()));
    const wt = c[8].split('/').map((s) => s.trim());
    const wallHex = hexIn(wt[0]), trimHex = hexIn(wt[1] || ''), wallPhoto = /\bv\b/.test(wt[0]), trimPhoto = /\bv\b/.test(wt[1] || '');
    const stor = Number(/\d+/.exec(c[6])[0]);
    const roofHex = (() => { const m = /roof[^#;.]{0,40}(#[0-9a-fA-F]{6})/i.exec(c[9] + ' ' + c[7]); return m ? m[1].toLowerCase() : null; })();
    out.push({ src: 'roster', key: c[0], addr: c[2], name: c[1], osm: c[3], x: xz[0], z: xz[1], storeys: stor, storeysSource: 'roster', style: c[7], era: c[7], wall: wallPhoto ? wallHex : null, wallGuess: wallPhoto ? null : wallHex,
      trim: trimPhoto || wallPhoto ? trimHex : null, roof: roofHex, shop: '', features: c[9], notes: c[10], conf: c[11].trim()[0] || 'L', photos: [c[12]] });
  }
  return out;
}

// ---------------------------------------------------------------- collect
const rep = { tables: {}, missing: [], rows: 0, idMatch: 0, ptMatch: 0, unmatched: [], claimed: [], dup: 0, placeholder: [], curated: 0, fromRows: 0, notes: [] };
const rowsAll = [];
const roster = rosterRows();
rep.tables.roster = { rows: roster.length, applied: 0, H: 0, M: 0, L: 0 };
for (const r of roster) rowsAll.push(r);
for (const t of TABLES) {
  const f = path.join(root, `docs/research/${t}-houses.json`);
  if (!fs.existsSync(f)) { rep.missing.push(t); continue; }
  let arr; try { arr = JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { rep.notes.push(`${t}: unreadable JSON (${e.message})`); rep.missing.push(t); continue; }
  if (!Array.isArray(arr)) arr = arr.houses || arr.rows || Object.values(arr);
  rep.tables[t] = { rows: arr.length, applied: 0, H: 0, M: 0, L: 0 };
  for (const r of arr) rowsAll.push({ ...r, src: t });
}
rowsAll.sort((p, q) => (RANK[q.conf] || 0) - (RANK[p.conf] || 0));          // the better-researched row of a house in two tables wins
const known = {}, seen = new Set(), merged = [];
for (const row of rowsAll) {
  rep.rows++;
  const mrow = { src: row.src, addr: row.addr, name: row.name || null, osm: row.osm, conf: row.conf || 'L', x: row.x, z: row.z };
  let b = byId.get(row.osm), how = 'id';
  if (!b && row.x != null) { b = D.BUILDINGS.find((q) => !q.skip && !(q.minH > 3) && q.polys.some((p) => inRing(p.o, row.x, row.z))); how = 'pt'; }
  if (!b) { rep.unmatched.push(`${row.src}: ${row.addr} ${row.osm}`); mrow.status = 'unmatched'; merged.push(mrow); continue; }
  if (how === 'id') rep.idMatch++; else rep.ptMatch++;
  mrow.id = b.id;
  if (seen.has(b.id)) { rep.dup++; mrow.status = 'duplicate (better row used)'; merged.push(mrow); continue; }
  seen.add(b.id);
  const claim = L.groupOf(b.id) || (b.parent && L.groupOf(b.parent));
  if (claim) { rep.claimed.push(`${b.id} ${claim} ${row.addr || row.name || ''}`); mrow.status = `claimed by ${claim}: the module draws it`; merged.push(mrow); continue; }
  if (CURATED[b.id]) { mrow.status = 'curated'; merged.push(mrow); continue; }
  const levels = b.levels ? Math.round(b.levels) : 0;
  const f = typeof row.storeys === 'number' && row.storeys > 0 ? row.storeys : levels;
  const year = yearOf(row), wall = hexIn(row.wall);
  const featText = (String(row.features || '') + ' ' + String(row.notes || '')).toLowerCase();
  const researched = !!(row.style || wall || row.features) && !/not researched in depth/i.test(String(row.notes || '')) && !(row.conf === 'L' && !wall && !year && !/art nouveau|neoclass|baroque|classicism|stalin|eclectic|brick|constructiv/i.test(String(row.style || '')));
  if (!researched) { rep.placeholder.push(`${b.id} ${row.addr || ''}`); mrow.status = 'placeholder: the island grammar decides'; merged.push(mrow); continue; }
  const a = archOf(row, f || 4, year, featText, Math.abs(b.area || 0));
  if (!a && !wall) { rep.placeholder.push(`${b.id} ${row.addr || ''} (style not recognised: ${String(row.style).slice(0, 40)})`); mrow.status = 'placeholder (style not recognised)'; merged.push(mrow); continue; }
  const e = { n: String(row.addr || row.name || b.id).slice(0, 48), c: row.conf || 'L', src: row.src };
  if (a) e.a = a;
  if (f && f !== levels) e.f = Math.min(f, 12);
  const photoH = typeof row.hCornice === 'number' && /photo|фото/i.test(String(row.hSource || '')) && (row.conf === 'H' || row.conf === 'M');
  if (photoH && Math.abs(row.hCornice - L.heightOf(b)) > 1) { e.H = Math.round(row.hCornice * 10) / 10; if (!e.f && f) e.f = f; }
  if (wall) e.hex = wall;
  const tc = trimClassOf(row.trim, wall); if (tc !== undefined && a !== 'SERVICE' && a !== 'COURT' && a !== 'NORDIC') e.tr = tc;
  const rh = hexIn(row.roof); if (rh) e.rf = rh;
  if (a) Object.assign(e, featuresOf(row, a, f));
  if (year) e.y = year;
  known[b.id] = e; rep.fromRows++; rep.tables[row.src][e.c] = (rep.tables[row.src][e.c] || 0) + 1; rep.tables[row.src].applied++;
  mrow.status = 'known'; mrow.entry = e; merged.push(mrow);
}
for (const [id, c] of Object.entries(CURATED)) {
  const b = byId.get(id);
  if (!b) { rep.notes.push(`curated id not in the baked data: ${id}`); continue; }
  if (L.isClaimed(id)) { rep.claimed.push(`${id} ${L.groupOf(id)} (curated: skipped)`); continue; }
  known[id] = { n: (b.addr ? `${b.addr.street || ''}, ${b.addr.no || ''}` : b.name || id).slice(0, 48), ...c, src: 'curated' };
  rep.curated++;
  const mr = merged.find((m) => m.id === id); if (mr) mr.entry = known[id]; else merged.push({ src: 'curated', addr: known[id].n, osm: id, id, conf: c.c || 'M', status: 'known', entry: known[id] });
}
// a curated `del` list: ids whose generated entry is wrong and must not exist
const existing = (await import(pathToFileURL(KD_FILE).href + '?t=' + Date.now())).KNOWN_DATA;
const text0 = fs.readFileSync(KD_FILE, 'utf8'), m0 = BEGIN_RE.exec(text0);
const oldBlock = m0 ? text0.slice(m0.index) : '';
for (const id of Object.keys(known)) if (existing[id] && !oldBlock.includes(JSON.stringify(id) + ':')) rep.notes.push(`${id} is also in an older KNOWN block (this block is assigned later and wins)`);

// ---------------------------------------------------------------- report + write
const conf = { H: 0, M: 0, L: 0 }, arch = {}; let turrets = 0;
for (const e of Object.values(known)) { conf[e.c] = (conf[e.c] || 0) + 1; arch[e.a || '-'] = (arch[e.a || '-'] || 0) + 1; if (e.tu) turrets++; }
if (args.has('--print')) for (const [id, e] of Object.entries(known)) console.log(id, JSON.stringify(e));
console.log(JSON.stringify({ rows: rep.rows, matchedById: rep.idMatch, matchedByPoint: rep.ptMatch, unmatched: rep.unmatched.length, duplicates: rep.dup, claimedSkipped: rep.claimed.length, placeholdersSkipped: rep.placeholder.length, entries: Object.keys(known).length, fromRows: rep.fromRows, curated: rep.curated, turrets, confidence: conf }));
console.log('tables:', JSON.stringify(rep.tables));
console.log('archetypes:', JSON.stringify(arch));
if (rep.unmatched.length) console.log('unmatched:', rep.unmatched);
if (args.has('--list')) { console.log('claimed (owned by a landmark module):', rep.claimed); console.log('placeholders (the island grammar decides):', rep.placeholder.length, rep.placeholder.slice(0, 40)); }
if (rep.notes.length) console.log('notes:', rep.notes.length, rep.notes.slice(0, 12));

if (!args.has('--dry')) {
  let text = text0;
  if (m0) { const e = text.indexOf(END, m0.index); const after = e >= 0 ? text.slice(e + END.length).replace(/^\s*/, '') : ''; text = text.slice(0, m0.index).replace(/\s*$/, '\n') + (after ? '\n' + after : ''); }
  if (text.length && !text.endsWith('\n')) text += '\n';
  const lines = Object.entries(known).map(([id, e]) => '  ' + JSON.stringify(id) + ': ' + JSON.stringify(e) + ',');
  const block = `${BEGIN}\n// ${Object.keys(known).length} houses of Vasilievsky Island (docs/research/vo-houses.json = the merged table of the roster section 8 + the 16 sight tables + tools/city-known-vo-curated.mjs);\n// c = confidence H / M (dossier, photo-checked or dated), L (knowledge of the place); y = year; no hex = the colour comes from the island palette at run time.\nObject.assign(KNOWN_DATA, {\n${lines.join('\n')}\n});\n${END}\n`;
  fs.writeFileSync(KD_FILE, text + block);
  fs.writeFileSync(OUT_JSON, JSON.stringify(merged, null, 1) + '\n');
  console.log('wrote', Object.keys(known).length, 'entries into', path.relative(root, KD_FILE), 'and', merged.length, 'rows into', path.relative(root, OUT_JSON));
}
