// Which page of which area a tool opens (docs/AREAS.md section 5). Shared by the browser tools (shot, smoke, drive-bench, drive-test, load-test, serve, baked-check) and the generator.
//   --page <file>   an HTML page of the site root (north.html); the area is the registry row whose page it is (or the page's own <html data-area> when it is not registered: a fixture)
//   --area <id>     a registry row; its page
//   neither         the strip (strip.html, the parked scene: the registry row's own page). index.html is the page of the live area 'palace' since the world-map re-cut: ask for it with --area palace / --page index.html
// A tool that also reads the area's TABLES (layout.js HERO / VIEWS ...) calls activateArea() BEFORE it imports layout.js: it registers the same module-loader remap that tools/area.mjs
// registers (and that the page's import map gives the browser), so `node tools/shot.mjs --area north` sees the north layout without being started through tools/area.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REGISTRY } from '../../src/areas/registry.js';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const flag = (v) => (v === undefined || v === '1' || v === true ? null : String(v));      // "--page" without a value parses as '1': treat as absent

/** The registry rows that are real (not 'planned'): the areas whose files exist and which the tools may bake / test / serve. */
export const realAreas = () => Object.values(REGISTRY).filter((a) => a.status !== 'planned');

/**
 * args: the parsed flags of the tool ({ page, area }).  Returns { id, page, row, planned }.  Throws (with a message that names the way out) for an unknown area, a page outside the site
 * root, a --page that belongs to another area than --area, or a page that does not exist.
 */
export function resolveArea(args = {}, siteRoot = root) {
  const want = flag(args.area), file = flag(args.page);
  let row = null, page = null;
  if (want) {
    row = REGISTRY[want];
    if (!row) throw new Error(`unknown area "${want}" (known: ${Object.keys(REGISTRY).join(', ')})`);
  }
  if (file) {
    page = file.replaceAll('\\', '/').replace(/^\.\//, '');
    if (/[/?#]/.test(page) || !/\.html$/.test(page)) throw new Error(`--page must be an .html file in the site root (got "${file}")`);
    const owner = Object.values(REGISTRY).find((r) => r.page === page) || null;
    if (row && owner && owner !== row) throw new Error(`--page ${page} belongs to area "${owner.id}", not "${row.id}"`);
    if (row && !owner && page !== row.page) { /* a fixture page for a registered area: allowed */ }
    if (!row) {
      if (owner) row = owner;
      else {
        const f = path.join(siteRoot, page), m = fs.existsSync(f) ? /<html[^>]*\sdata-area="([^"]+)"/.exec(fs.readFileSync(f, 'utf8')) : null;
        row = (m && REGISTRY[m[1]]) || REGISTRY.strip;
      }
    }
  }
  row ??= REGISTRY.strip;
  page ??= row.page;
  if (!fs.existsSync(path.join(siteRoot, page))) {
    throw new Error(`page ${page} does not exist${row.status === 'planned' ? ` (area "${row.id}" is planned: its page is generated by node tools/gen-area-html.mjs --area ${row.id} --force-planned once its files exist)` : ''}`);
  }
  return { id: row.id, page, row, planned: row.status === 'planned' };
}

/**
 * Make `import('.../src/world/layout.js')` (and every importer of the data facade) see the area's files, like the area's import map does. A no-op for the strip.
 * Safe to call when tools/area.mjs already registered the same hooks (the second remap finds nothing left to remap).
 */
export async function activateArea(row, siteRoot = root) {
  process.env.AREA = row.id;
  if (!row.remap || !Object.keys(row.remap).length) return;
  for (const v of Object.values(row.remap)) {
    if (!fs.existsSync(path.join(siteRoot, v))) throw new Error(`area "${row.id}": ${v} does not exist${row.status === 'planned' ? ' (the area is planned: its data and area module have not landed yet)' : ''}`);
  }
  const { register } = await import('node:module');
  register('./area-hooks.mjs', { parentURL: import.meta.url, data: { root: siteRoot, remap: row.remap } });
}

/** The page URL path of an area on a server rooted at the site root: '/index.html' (BASE = '' or '/n4spb'). */
export const pagePath = (page, base = '') => `${base}/${page}`;

/** Parse "--k v" / "--flag" arguments the way the tools do ("--flag" followed by another flag or nothing is '1'). */
export function parseFlags(argv = process.argv.slice(2)) {
  const args = {};
  for (let i = 0; i < argv.length; i++) { const a = argv[i]; if (a.startsWith('--')) { const k = a.slice(2); args[k] = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : '1'; } }
  return args;
}
