// tools/streets-late-roads.mjs - write src/world/data/late-roads.js: the roads of tools/late-roads-ids.mjs as ROADS records, taken from the raw layer data/osm-raw/roads.json WITHOUT a bake
// (a bake keeps the record shape: this tool repeats the few lines of tools/bake-osm.mjs bakeRoads that make a record; keep the two in step).
// usage: node tools/streets-late-roads.mjs [--empty]      --empty writes an empty list (after a bake that holds the roads in ROADS: streets/net.js skips ids that ROADS holds anyway)
// Why a separate file: a record added to a part file would shift the index of every later way (the streets module hashes w.i); this one is appended after ROADS in net.js rawWays.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { proj, simplify, flat, clipLineUnion, EXTENT_RECTS, round1 } from './osm-lib.mjs';
import { LATE_ROAD_IDS } from './late-roads-ids.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const num = (v) => { if (v == null) return null; const m = String(v).replace(',', '.').match(/-?\d+(\.\d+)?/); return m ? parseFloat(m[0]) : null; };
const compact = (o) => { for (const k of Object.keys(o)) if (o[k] == null || o[k] === '') delete o[k]; return o; };
const ROAD_W = { secondary: 7.5, tertiary: 6.5, residential: 6, unclassified: 5.5, service: 4 };
const roadWidth = (t) => { const w = num(t.width); if (w) return w; const lanes = num(t.lanes); if (lanes) { const base = lanes * 3.4 + 0.4; return t.oneway === 'yes' || t.oneway === '-1' ? base : Math.max(base, 5.5); } return ROAD_W[t.highway] || 4; };
const CLASSES = new Set(['secondary', 'tertiary', 'residential', 'unclassified', 'service']);
/** the class of a way that is under construction: its construction=* value when it is a road class, else residential */
export const classOfLate = (t) => (CLASSES.has(t.construction) ? t.construction : 'residential');
const yes = (v) => v === 'yes' || v === 'true' || v === '1';

const out = path.join(root, 'src', 'world', 'data', 'late-roads.js');
const recs = [];
if (!process.argv.includes('--empty')) {
  const j = JSON.parse(fs.readFileSync(path.join(root, 'data', 'osm-raw', 'roads.json'), 'utf8'));
  for (const e of j.elements || j) {
    if (e.type !== 'way' || !LATE_ROAD_IDS.has(e.id) || !e.geometry) continue;
    const t = { ...(e.tags || {}), highway: classOfLate(e.tags || {}) };
    const pts = e.geometry.map((n) => proj(n.lon, n.lat));
    for (const seg of clipLineUnion(pts, EXTENT_RECTS)) {
      const s = simplify(seg, 0.3); if (s.length < 2) continue;
      recs.push(compact({
        id: 'w' + e.id, hw: t.highway, name: t.name || t['name:ru'] || null, nameEn: t['name:en'] || t.int_name || null, w: round1(roadWidth(t)), lanes: num(t.lanes),
        oneway: t.oneway === 'yes' ? 1 : t.oneway === '-1' ? -1 : 0, surface: t.surface || null, bridge: 0, tunnel: 0, passage: 0, layer: num(t.layer) ?? 0, area: 0,
        lit: yes(t.lit) ? 1 : 0, maxspeed: num(t.maxspeed), late: 1, pts: flat(s),
      }));
    }
  }
}
const lines = ['// GENERATED by tools/streets-late-roads.mjs - roads that the bake drops (highway=construction) but that are lasting streets (tools/late-roads-ids.mjs). OpenStreetMap data (c) OpenStreetMap contributors, ODbL',
  `export const LATE_ROADS = ${JSON.stringify(recs)};`, ''];
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(root, out)}: ${recs.length} record(s)`, recs.map((r) => `${r.id} ${r.name || ''} ${r.hw} w${r.w} oneway ${r.oneway} ${Math.round(r.pts.length / 2)} pts`).join('; '));
