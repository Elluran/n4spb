// tools/landmarksNewHolland-extract.mjs - writes src/world/landmarksNewHolland/osm-data.js: the OSM point / line features of New Holland island that the baked city data lacks or thins out
// (every natural=tree node with its species, the tree rows, benches, litter bins, street lamps, the island ring and the playground / pier details), projected with tools/osm-lib.mjs.
// usage: node tools/landmarksNewHolland-extract.mjs [--xml path/to/map.osm]     (default: fetch https://api.openstreetmap.org/api/0.6/map?bbox=30.2830,59.9255,30.2960,59.9325)
// Data (c) OpenStreetMap contributors, ODbL.  Re-run only when the map changes; the output is committed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { proj } from './osm-lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const xmlArg = argv.indexOf('--xml') >= 0 ? argv[argv.indexOf('--xml') + 1] : null;
const BBOX = '30.2830,59.9255,30.2960,59.9325';
let xml;
if (xmlArg) xml = fs.readFileSync(xmlArg, 'utf8');
else {
  const r = await fetch(`https://api.openstreetmap.org/api/0.6/map?bbox=${BBOX}`, { headers: { 'User-Agent': 'piter-anime-walk/1.0 (research; nepo7771@gmail.com)' } });
  if (!r.ok) throw new Error('OSM map API ' + r.status);
  xml = await r.text();
}
const unesc = (s) => s.replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const nodes = {}, ways = {}, rels = {};
const re = /<(node|way|relation) ([^>]*?)(\/>|>([\s\S]*?)<\/\1>)/g;
let m;
while ((m = re.exec(xml))) {
  const [, kind, attrs, , body] = m;
  const id = +/id="(\d+)"/.exec(attrs)[1];
  const tags = {};
  if (body) for (const t of body.matchAll(/<tag k="([^"]*)" v="([^"]*)"\/>/g)) tags[unesc(t[1])] = unesc(t[2]);
  if (kind === 'node') { const [x, z] = proj(+/lon="([^"]+)"/.exec(attrs)[1], +/lat="([^"]+)"/.exec(attrs)[1]); nodes[id] = { x, z, tags }; }
  else if (kind === 'way') ways[id] = { nd: [...body.matchAll(/<nd ref="(\d+)"/g)].map((a) => +a[1]), tags };
  else rels[id] = { mem: [...body.matchAll(/<member type="(\w+)" ref="(\d+)" role="([^"]*)"/g)].map((a) => ({ t: a[1], ref: +a[2], role: a[3] })), tags };
}
// the island ring: relation r1576204, outer ways chained
const rel = rels[1576204];
if (!rel) throw new Error('relation 1576204 missing from the fetch');
const segs = rel.mem.filter((q) => q.t === 'way').map((q) => ways[q.ref].nd.slice());
const chain = segs.shift();
while (segs.length) {
  const end = chain[chain.length - 1];
  const i = segs.findIndex((s) => s[0] === end || s[s.length - 1] === end);
  if (i < 0) throw new Error('ring gap');
  const s = segs.splice(i, 1)[0]; if (s[0] !== end) s.reverse(); chain.push(...s.slice(1));
}
const ring = chain.slice(0, -1).map((n) => [nodes[n].x, nodes[n].z]);
const inside = (x, z, p) => { let c = false; for (let i = 0, j = p.length - 1; i < p.length; j = i++) { const [xi, zi] = p[i], [xj, zj] = p[j]; if ((zi > z) !== (zj > z) && x < (xj - xi) * (z - zi) / (zj - zi) + xi) c = !c; } return c; };
const r1 = (v) => Math.round(v * 10) / 10;
const trees = [], lamps = [], benches = [], bins = [], racks = [], rows = [];
const fam = (t) => {
  const s = (t['species:ru'] || '') + ' ' + (t.genus || '') + ' ' + (t.taxon || '');
  if (/Picea|ель/i.test(s)) return 'spruce';
  if (/дуб|Quercus/i.test(s)) return 'oak';
  if (/Acer|клен|клён/i.test(s)) return 'maple';
  if (/липа|Tilia/i.test(s)) return 'lime';
  return 'tree';
};
for (const n of Object.values(nodes)) {
  if (!inside(n.x, n.z, ring)) continue;
  const t = n.tags;
  if (t.natural === 'tree') trees.push([r1(n.x), r1(n.z), fam(t)]);
  else if (t.highway === 'street_lamp') lamps.push([r1(n.x), r1(n.z)]);
  else if (t.amenity === 'bench') benches.push([r1(n.x), r1(n.z)]);
  else if (t.amenity === 'waste_basket') bins.push([r1(n.x), r1(n.z)]);
  else if (t.amenity === 'bicycle_parking') racks.push([r1(n.x), r1(n.z), +t.capacity || 10]);
}
for (const w of Object.values(ways)) {
  if (w.tags.natural !== 'tree_row') continue;
  const pts = w.nd.map((id) => nodes[id]).filter(Boolean);
  if (pts.length >= 2 && inside(pts[0].x, pts[0].z, ring)) rows.push(pts.map((p) => [r1(p.x), r1(p.z)]));
}
const J = (a) => '[' + a.map((r) => JSON.stringify(r)).join(',') + ']';
const out = `// GENERATED by tools/landmarksNewHolland-extract.mjs from OpenStreetMap (c) OpenStreetMap contributors, ODbL: the point features of New Holland island (relation r1576204).
// ISLAND_RING [x,z]..; TREES [x,z,family] (family: lime / oak / maple / spruce / tree); TREE_ROWS polylines of young limes; LAMPS, BENCHES, BINS [x,z]; RACKS [x,z,capacity].
export const ISLAND_RING = ${J(ring.map((p) => [r1(p[0]), r1(p[1])]))};
export const TREES = ${J(trees)};
export const TREE_ROWS = ${J(rows)};
export const LAMPS = ${J(lamps)};
export const BENCHES = ${J(benches)};
export const BINS = ${J(bins)};
export const RACKS = ${J(racks)};
`;
fs.writeFileSync(path.join(root, 'src/world/landmarksNewHolland/osm-data.js'), out);
console.log('ring', ring.length, 'trees', trees.length, 'rows', rows.length, 'lamps', lamps.length, 'benches', benches.length, 'bins', bins.length, 'racks', racks.length);
