import assert from 'node:assert/strict';
import * as THREE from 'three';
import { privateStaticBatch, compactStaticAttributes } from '../src/core/compact-static.js';
import { releaseOnUpload, releasedStats } from '../src/core/spatial.js';
const root = new THREE.Group(), g = new THREE.SphereGeometry(7, 48, 24), mat = new THREE.MeshBasicMaterial({ vertexColors: true });
const colours = new Float32Array(g.attributes.position.count * 3);
for (let i = 0; i < colours.length; i++) colours[i] = (i * 17 % 1001) / 1000;
g.setAttribute('color', new THREE.BufferAttribute(colours, 3)); g.computeBoundingBox(); g.computeBoundingSphere();
root.add(new THREE.Mesh(privateStaticBatch(g), mat));
const normal = g.attributes.normal.array.slice(), colour = g.attributes.color.array.slice(), position = g.attributes.position, uv = g.attributes.uv, index = g.index;
const source = g.clone(); root.add(new THREE.Mesh(source, mat));
const sourceNormal = source.attributes.normal, sourceColour = source.attributes.color;
const hdr = privateStaticBatch(g.clone()); hdr.attributes.color.array[0] = 1.7; root.add(new THREE.Mesh(hdr, mat));
const dynamic = privateStaticBatch(g.clone()); dynamic.attributes.normal.setUsage(THREE.DynamicDrawUsage); root.add(new THREE.Mesh(dynamic, mat));
const box = g.boundingBox.clone(), sphere = g.boundingSphere.clone(); releaseOnUpload(g);
const result = compactStaticAttributes(root); assert(result.savedBytes > 0);
assert.equal(g.attributes.position, position); assert.equal(g.attributes.uv, uv); assert.equal(g.index, index);
assert(g.boundingBox.equals(box)); assert(g.boundingSphere.equals(sphere));
assert(g.attributes.normal.array instanceof Int16Array); assert(g.attributes.color.array instanceof Uint16Array);
for (let i = 0; i < normal.length; i++) assert(Math.abs(g.attributes.normal.getComponent(Math.floor(i / 3), i % 3) - normal[i]) <= 1 / 65534);
for (let i = 0; i < colour.length; i++) assert(Math.abs(g.attributes.color.getComponent(Math.floor(i / 3), i % 3) - colour[i]) <= 1 / 131070);
assert.equal(source.attributes.normal, sourceNormal); assert.equal(source.attributes.color, sourceColour);
assert(hdr.attributes.color.array instanceof Float32Array); assert.equal(hdr.attributes.color.array[0], Math.fround(1.7));
assert(dynamic.attributes.normal.array instanceof Float32Array);
assert.equal(compactStaticAttributes(root).savedBytes, 0, 'compaction is idempotent');
const bytes = g.attributes.normal.array.byteLength + g.attributes.color.array.byteLength, before = releasedStats.bytes;
g.attributes.normal.onUploadCallback(); g.attributes.color.onUploadCallback();
assert.equal(releasedStats.bytes - before, bytes); assert.equal(g.attributes.normal.array.length, 0); assert.equal(g.attributes.color.array.length, 0);
console.log(`RESULT: OK (${result.savedBytes} bytes saved; precision bounds, exact positions/UVs/topology, shared originals, HDR, dynamics and upload lifetime)`);
